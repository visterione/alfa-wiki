import {useSafeAreaInsets} from 'react-native-safe-area-context';

/**
 * Место, которое занимает плавающая кнопка «Альфа».
 *
 * Кнопка лежит поверх экранов, а не рядом с ними (см. AlfaTabBar), поэтому
 * высоту под неё экраны резервируют сами — отступом снизу у прокручиваемого
 * содержимого и у всего, что прижато к нижнему краю.
 *
 * Отдельным модулем, а не константой в AlfaTabBar: иначе каждый экран тянул бы
 * за собой всю панель с её градиентами и анимациями ради одного числа.
 *
 * Число осталось прежним (68) и после перехода на дугу разделов: ряда вкладок
 * больше нет, но знак стал крупнее и приподнят над жестовой полосой, так что
 * закрывает он ровно столько же.
 */

export const TAB_BAR_HEIGHT = 68;

/** Высота кнопки вместе с жестовой полосой под ней. */
export function useTabBarInset() {
  const insets = useSafeAreaInsets();
  return TAB_BAR_HEIGHT + insets.bottom;
}
