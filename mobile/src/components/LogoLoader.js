import React, {useEffect, useRef} from 'react';
import {View, Animated, Easing} from 'react-native';
import Svg, {Path} from 'react-native-svg';
import {useTheme} from '../store/settingsStore';

/**
 * Индикатор загрузки — логотип, который рисует сам себя.
 *
 * Как это устроено: обе линии логотипа нарисованы пунктиром, у которого длина
 * штриха равна всей длине линии, а промежуток вдвое больше. Такой пунктир — это
 * ровно один штрих; сдвигая его вдоль линии (strokeDashoffset), мы показываем
 * её по частям. Смещение, равное длине, уводит штрих за начало линии — её не
 * видно совсем; нулевое смещение кладёт штрих точно на линию — видно целиком.
 * Промежуток вдвое длиннее нужен затем, чтобы второй штрих пунктира не подполз
 * с другого конца, пока первый ещё не на месте.
 *
 * Тело логотипа (BODY) рисуется вперёд, от правой ноги к середине. Хвостик
 * (TAIL) — наоборот, задом наперёд: он появляется сверху и дотягивается
 * вниз-вправо. Отсюда и знаки смещения: положительное прячет штрих перед
 * началом линии, отрицательное — за её концом.
 *
 * Почему JS-анимация, а не нативная, как была у кардиограммы: там двигались
 * обычные View, и это можно отдать нативному драйверу. Здесь меняется свойство
 * самой SVG-линии, а такие свойства нативный драйвер не умеет — значение на
 * каждом кадре приходит из JS. Если JS-поток занят тяжёлой работой (не
 * ожиданием сети — ожидание его не блокирует, а разбором большого ответа или
 * первой отрисовкой длинного списка), рисование на этот момент замрёт. Обойти
 * это без новой зависимости (reanimated или skia) нельзя.
 *
 * @param {number} width  ширина в px, высота считается сама (2:1)
 * @param {string} color  цвет линий; на цветном фоне передают '#FFFFFF'
 * @param {number} duration  длительность одного цикла, мс
 */

const AnimatedPath = Animated.createAnimatedComponent(Path);

// Кадрирование по самой фигуре, а не по холсту из Inkscape: у исходного файла
// поля с четырёх сторон разные, и логотип стоял бы в контейнере со сдвигом.
// Здесь рамка ровно 2:1 вокруг фигуры с учётом толщины линии.
const VIEW_BOX = '20.3 12.5 352 176';
const RATIO = 2;
const STROKE = 20;

// Тело логотипа: от правой ноги вверх, через всю дугу, к середине.
const BODY = [
  'm 361.89568 178.32852',
  'c',
  '-24.05556 0.30509 -35.92304 -42.54269 -48.94664 -75.04483',
  '-10.53638 -26.294944 -26.20207 -67.801566 -55.49886 -68.159741',
  '-20.70063 -0.253081 -39.95582 26.52193 -46.35764 38.666839',
  '-6.90377 13.097152 -10.18538 20.629861 -15.48803 30.837532',
  '-3.51152 6.75971 -6.92017 13.58436 -10.81067 20.13329',
  '-4.72091 7.94678 -9.11464 16.23109 -15.18079 23.20535',
  '-6.35253 7.30351 -13.62621 14.02764 -21.86288 19.11224',
  '-6.43024 3.96947 -12.07539 6.13781 -20.98743 8.57148',
  '-11.28607 3.08196 -21.9418 3.17976 -34.081731 0.86834',
  '-8.452478 -1.60933 -15.656046 -4.65312 -23.015328 -9.1113',
  '-6.927817 -4.1968 -14.211997 -9.00084 -19.360874 -15.25358',
  '-5.738907 -6.96927 -11.460921 -15.56207 -14.838071 -24.48921',
  '-3.138674 -8.29674 -4.526054 -17.32025 -4.72701 -26.18856',
  '-0.184079 -8.123522 0.656852 -16.456252 3.238945 -24.160685',
  '3.273479 -9.767384 8.610342 -18.984513 15.180783 -26.918412',
  '6.007149 -7.253716 13.39004 -13.595071 21.59297 -18.222615',
  '7.941776 -4.480218 16.906526 -7.335607 25.911563 -8.768596',
  '8.311703 -1.322658 15.164903 -0.961669 25.247413 0.269911',
  '13.36365 1.63237 30.60859 6.870226 40.82493 15.893967',
  '9.94304 8.782333 15.84698 19.397617 22.04081 33.137485',
].join(' ');

// Хвостик. В файле он описан снизу вверх, а рисуется наоборот — сверху вниз.
const TAIL = [
  'm 241.40253 178.35591',
  'c',
  '-19.35693 1.64756 -32.18962 -32.11967 -33.60418 -44.86674',
].join(' ');

// Длины линий посчитаны по кривым Безье и округлены вверх: если взять длину
// меньше настоящей, штрих окажется короче линии и её хвост никогда не дорисуется.
const BODY_LEN = 748;
const TAIL_LEN = 61;

// Запас в один шаг сетки. Ровно на длине линии штрих касается её конца одной
// точкой, а точка при круглом торце рисуется кружком — на пустом экране висела
// бы клякса. Запас уводит штрих чуть дальше, чем нужно.
const PAD = 1;

/* ── Раскадровка ───────────────────────────────────────────────────────────
 *
 * Считаем в кадрах при 60 к/с — в них анимация и задумана, поэтому длительность
 * выводится из раскадровки, а не наоборот. Пауз две, и обе не декоративные:
 * пустая в начале отделяет один проход от другого, иначе на стыке цикла линия
 * начинала бы рисоваться в тот же миг, как исчезла, и повтор читался бы рывком.
 * Пауза в конце даёт задержать взгляд на собранном логотипе — ради неё
 * анимация и затевалась.
 */
const FRAMES = {hold: 10, body: 50, tail: 20, rest: 10};
const TOTAL = FRAMES.hold + FRAMES.body + FRAMES.tail + FRAMES.rest;
const FPS = 60;

// Границы этапов как доли цикла — в таком виде их ждёт interpolate
const AT_DRAW = FRAMES.hold / TOTAL;
const AT_TAIL = (FRAMES.hold + FRAMES.body) / TOTAL;
const AT_REST = (FRAMES.hold + FRAMES.body + FRAMES.tail) / TOTAL;

export default function LogoLoader({
  width = 96,
  color,
  duration = (TOTAL / FPS) * 1000,
  style,
}) {
  const c = useTheme();
  const stroke = color || c.primary;
  const height = width / RATIO;

  const progress = useRef(new Animated.Value(0)).current;

  useEffect(() => {
    progress.setValue(0);
    const draw = Animated.loop(
      Animated.timing(progress, {
        toValue: 1,
        duration,
        // Линейно: рука ведёт линию с одной скоростью, разгон и торможение
        // читались бы как рывок на стыке двух линий
        easing: Easing.linear,
        useNativeDriver: false,
        // Индикатор крутится, пока идёт загрузка, и не должен считаться
        // взаимодействием: иначе отложенная через InteractionManager работа
        // не начнётся никогда
        isInteraction: false,
      }),
    );
    draw.start();
    return () => draw.stop();
  }, [progress, duration]);

  // Тело: пережидает первую паузу спрятанным, рисуется, дальше стоит целым
  const bodyOffset = progress.interpolate({
    inputRange: [0, AT_DRAW, AT_TAIL, 1],
    outputRange: [BODY_LEN + PAD, BODY_LEN + PAD, 0, 0],
  });

  // Хвостик: ждёт, пока дорисуется тело, и выезжает из-за своего конца
  const tailOffset = progress.interpolate({
    inputRange: [0, AT_TAIL, AT_REST, 1],
    outputRange: [-(TAIL_LEN + PAD), -(TAIL_LEN + PAD), 0, 0],
  });

  return (
    <View style={[{width, height}, style]} pointerEvents="none">
      <Svg width={width} height={height} viewBox={VIEW_BOX}>
        <AnimatedPath
          d={BODY}
          stroke={stroke}
          strokeWidth={STROKE}
          strokeLinecap="round"
          strokeLinejoin="round"
          fill="none"
          strokeDasharray={[BODY_LEN, BODY_LEN * 2]}
          strokeDashoffset={bodyOffset}
        />
        <AnimatedPath
          d={TAIL}
          stroke={stroke}
          strokeWidth={STROKE}
          strokeLinecap="round"
          fill="none"
          strokeDasharray={[TAIL_LEN, TAIL_LEN * 2]}
          strokeDashoffset={tailOffset}
        />
      </Svg>
    </View>
  );
}
