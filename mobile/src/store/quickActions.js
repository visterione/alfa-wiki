/**
 * Быстрые действия, которые запускает панель навигации.
 *
 * Долгое нажатие на знак «Альфа» открывает колесо действий текущего раздела
 * (ver. 7.27), и часть этих действий живёт не в навигации, а внутри экрана:
 * «Новая задача» открывает лист быстрого создания прямо в TasksScreen, и
 * никаким переходом его не вызвать.
 *
 * Отсюда этот магазин: панель просит, экран исполняет. Тот же приём, что у
 * непрочитанных сообщений, — подписчик и источник в разных ветках дерева, — но
 * направление обратное: здесь событие идёт от панели к экрану.
 *
 * Просьба не копится: если экрана нет на месте, она просто не будет исполнена.
 * Отложенная «создать задачу», всплывающая через полчаса при возврате в раздел,
 * — это не то, чего человек ждёт.
 */
import {useEffect} from 'react';

const handlers = new Map();

/** Экран объявляет, что умеет исполнять действие. */
export function useQuickAction(name, handler) {
  useEffect(() => {
    handlers.set(name, handler);
    return () => {
      // Снимаем только свой обработчик: два экрана одного имени не бывает, но
      // при быстром переходе новый успевает записаться раньше, чем старый
      // размонтируется, и слепое удаление стёрло бы живой.
      if (handlers.get(name) === handler) handlers.delete(name);
    };
  }, [name, handler]);
}

/** Панель просит исполнить. Возвращает false, если исполнять некому. */
export function runQuickAction(name) {
  const handler = handlers.get(name);
  if (!handler) return false;
  handler();
  return true;
}
