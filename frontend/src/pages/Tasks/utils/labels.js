/**
 * Цвет загрузки — непрерывная шкала от нуля до нормы и дальше в переработку.
 *
 * До этого было три ступени: зелёный до 85% нормы, жёлтый до неё самой, красный
 * за ней. Ступени приходилось объяснять легендой, а главное — они врали на
 * границах: 84% и 86% выглядели как два разных состояния дня, зато 20% и 80%
 * как одно и то же. Непрерывный градиент показывает ровно ту величину, которая
 * есть, и подписи не требует: цвет меняется вместе с числом рядом.
 *
 * Опорные точки повторяют палитру темы, чтобы полосы не выпадали из интерфейса:
 * --success в нуле, --warning на 85% (там, где день перестаёт быть свободным),
 * --error на норме. Числами, а не переменными: значения между опорными точками
 * приходится считать, а css-переменную не смешаешь. Дальше цвет темнеет до края
 * шкалы в 1,4 нормы — переработку видно и по длине, но упираться в чистый
 * красный она должна не сразу.
 *
 * Зелёный держится до середины намеренно: полдня работы — это не «уже теплеет»,
 * и линейный ход от зелёного к оранжевому красил бы спокойные дни тревожно.
 */
const LOAD_SCALE = [
  [0, [52, 199, 89]],
  [0.55, [126, 207, 70]],
  [0.75, [214, 191, 48]],
  [0.85, [255, 149, 0]],
  [1, [255, 59, 48]],
  [1.4, [176, 27, 20]],
];

/** Доля нормы (1 = ровно норма) → цвет. Значение вне шкалы прижимается к краю. */
export function loadColor(ratio) {
  const value = Number.isFinite(ratio) ? Math.max(ratio, 0) : 0;
  const last = LOAD_SCALE[LOAD_SCALE.length - 1];
  if (value >= last[0]) return rgb(last[1]);

  for (let i = 1; i < LOAD_SCALE.length; i += 1) {
    const [to, toColor] = LOAD_SCALE[i];
    if (value > to) continue;
    const [from, fromColor] = LOAD_SCALE[i - 1];
    const t = (value - from) / (to - from);
    return rgb(fromColor.map((channel, k) => Math.round(channel + (toColor[k] - channel) * t)));
  }
  return rgb(LOAD_SCALE[0][1]);
}

function rgb([r, g, b]) {
  return `rgb(${r}, ${g}, ${b})`;
}

/** Инициалы для аватарки-заглушки. */
export function initials(user) {
  const name = user?.displayName || user?.username || '';
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (!parts.length) return '?';
  if (parts.length === 1) return parts[0][0].toUpperCase();
  return (parts[0][0] + parts[1][0]).toUpperCase();
}

/**
 * Цвет аватарки выводится из идентификатора, а не хранится.
 *
 * Палитра приглушённая: аватарки стоят рядами по всей таблице загрузки, и
 * насыщенные цвета там перебивают то единственное, что должно бросаться в
 * глаза — красную полосу переработки.
 */
const AVATAR_COLORS = [
  '#7FB3D5', '#7DCEA0', '#F5B041', '#C39BD3', '#76D7C4',
  '#F1948A', '#85C1E9', '#F7DC6F', '#BB8FCE', '#73C6B6',
];

export function avatarColor(id) {
  const key = String(id || '');
  let hash = 0;
  for (let i = 0; i < key.length; i += 1) hash = (hash * 31 + key.charCodeAt(i)) >>> 0;
  return AVATAR_COLORS[hash % AVATAR_COLORS.length];
}

export function userName(user) {
  return user?.displayName || user?.username || 'Без имени';
}

/**
 * Код части: РЕМ-42/2.
 *
 * Номер части считается по её месту в задаче и вычисляется на месте, а не
 * хранится: сам код задачи неизменен, а порядок частей — это порядок работы, и
 * он живёт своей жизнью. Задачи без кода (созданные до ver. 6.94 и ещё не
 * прошедшие миграцию) отдают пустую строку — интерфейс просто ничего не рисует.
 */
export function partCode(code, index) {
  if (!code) return '';
  return index === null || index === undefined ? code : `${code}/${Number(index) + 1}`;
}

/**
 * «Стеценко Виталий» — фамилия и имя, без отчества.
 *
 * В системе у людей полное ФИО, и в узких местах вроде шкал отчёта оно не
 * помещалось: имя обрезалось многоточием ровно там, где начинается отчество, и
 * половина списка выглядела одинаково. Отчество в этих списках ничего не
 * различает — однофамильцев с одинаковым именем в компании нет.
 */
export function shortName(user) {
  const full = userName(user);
  const parts = full.trim().split(/\s+/).filter(Boolean);
  return parts.length > 2 ? parts.slice(0, 2).join(' ') : full;
}

/**
 * Русское склонение при числе: plural(3, 'задача', 'задачи', 'задач').
 *
 * Нужно ровно там, где число приходит с сервера и не бывает известно заранее.
 * «1 командных задач» в заголовке показателя выглядит как недоделка, а
 * показатели читают в первую очередь — это первое, что видно на странице
 * команды.
 */
export function plural(count, one, few, many) {
  const n = Math.abs(Number(count) || 0) % 100;
  if (n > 10 && n < 20) return many;
  const last = n % 10;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

/**
 * «Стеценко Виталий» · «Виталий, Лидия» · «Виталий, Лидия +3».
 *
 * Для колонки исполнителей в списке задач. Раньше там стояло число рядом с
 * аватарками — «3», — и оно не отвечало на единственный вопрос, который к этой
 * колонке задают: кто это. Наводить курсор на каждую аватарку ради подсказки
 * никто не станет.
 *
 * Один человек показывается коротким именем целиком, несколько — только
 * именами: в узкой колонке «Стеценко Виталий, Белякова Лидия» обрезалось бы
 * ровно там, где начинается второе имя, и список превращался бы в одно имя с
 * многоточием. Имена, а не фамилии, — так в компании друг друга и зовут.
 */
export function peopleText(users, max = 2) {
  const list = (users || []).filter(Boolean);
  if (!list.length) return '';
  if (list.length === 1) return shortName(list[0]);
  const shown = list.slice(0, max).map(firstName).join(', ');
  return list.length > max ? `${shown} +${list.length - max}` : shown;
}

/**
 * Имя из ФИО: «Стеценко Виталий Витальевич» → «Виталий».
 *
 * У всех в системе записано полное ФИО, и имя в нём стоит вторым. Если слово
 * одно — это логин или название бота, и брать из него нечего.
 */
export function firstName(user) {
  const parts = userName(user).trim().split(/\s+/).filter(Boolean);
  return parts.length > 1 ? parts[1] : parts[0] || '';
}
