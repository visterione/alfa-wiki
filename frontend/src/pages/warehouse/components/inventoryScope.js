/**
 * Область инвентаризации одной строкой.
 *
 * С ver. 7.36 опись бывает по нескольким кабинетам сразу, и «Каб. 305» в ячейке
 * больше не отвечает на вопрос, что именно пересчитывают. Функция общая, потому
 * что область читают три места — журнал инвентаризаций, отчёт по описям и шапка
 * окна пересчёта, — и разные формулировки выглядели бы как разные описи.
 *
 * Номера, а не полные пути: в столбце помещается три-четыре, и различают описи
 * как раз номера. Длинный перечень урезается счётчиком — восемь номеров подряд
 * читаются хуже, чем «и ещё 5».
 */
export default function inventoryScopeText(session) {
  const rooms = session?.rooms?.length ? session.rooms : (session?.room ? [session.room] : []);
  if (rooms.length > 3) {
    return `Каб. ${rooms.slice(0, 3).map(r => r.number).join(', ')} и ещё ${rooms.length - 3}`;
  }
  if (rooms.length) return `Каб. ${rooms.map(r => r.number).join(', ')}`;
  return session?.department?.name || '—';
}
