/**
 * Поиск по названиям на экранах склада.
 *
 * Правило то же, что и на сервере (backend/services/warehouse/search.js), и это
 * важнее удобства: списки, приходящие целиком, фильтрует экран, а списки с
 * потолком — база, и один и тот же запрос должен вести себя одинаково в обоих
 * случаях. Разойдись они — человек решит, что позиции пропадают в зависимости
 * от того, на какой вкладке он их ищет.
 *
 * Запрос дробится на слова, и строка подходит, когда КАЖДОЕ слово нашлось хоть
 * в одном из полей, в любом порядке: «системный блок» должен находить «Блок
 * системный HP», потому что в названиях из 1С слова стоят как придётся.
 *
 * «ё» и «е» не различаются: в одной ведомости соседствуют «Ёмкость» и
 * «Емкость», и набравший одно не находил другого — со стороны это выглядело
 * как пропавшие позиции.
 */

const normalize = value => String(value || '').toLowerCase().replace(/ё/g, 'е');

/**
 * Запрос → слова. Односимвольные отбрасываются: они есть почти в каждом
 * названии и поиск не сужают. Но если после отсева не осталось ничего, берём
 * что дали: запрос «3» (номер кабинета) не должен означать «показать всё».
 */
export function searchWords(q) {
  const all = normalize(q).split(/[\s,;]+/).map(w => w.trim()).filter(Boolean);
  const long = all.filter(w => w.length >= 2);
  return long.length ? long : all;
}

/**
 * @param {string} q       строка запроса
 * @param {Array} values   значения полей строки (пустые игнорируются)
 */
export function matchesSearch(q, values) {
  const words = searchWords(q);
  if (!words.length) return true;
  const hay = normalize(values.filter(Boolean).join(' '));
  return words.every(word => hay.includes(word));
}
