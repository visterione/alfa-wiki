/**
 * Карта сети на экране входа: проекция и рамки камеры.
 *
 * Сама карта — статический файл public/map/anapa.svg: берег, зелень и улицы
 * выгружены из OpenStreetMap один раз и в бандл не попадают. Метки рисует
 * приложение поверх, координаты берёт из справочника медцентров.
 *
 * Константы ниже — не настройки, а часть договора с этим файлом. Он нарисован
 * ровно в этой проекции; поменять здесь число и не перерисовать файл — значит
 * развести метки с картой. Понадобится другой охват — карту надо выгружать
 * заново тем же расчётом.
 *
 * Оба файла в public/map — anapa.svg и routes.json — собирает
 * frontend/tools/build-login-map.py. Он ходит в Overpass, режет геометрию по
 * этой же проекции и считает маршруты по улицам. Запускается руками и редко:
 * когда переехал филиал, открылся новый или понадобился другой охват.
 *
 * Имя с суффиксом Geo не для красоты: файл loginMap.js отличался бы от
 * компонента LoginMap.js только регистром первой буквы, а на macOS и Windows
 * это один и тот же путь.
 */

// Прямоугольник охвата: от «Проф» на севере до Сукко на юге.
const LAT_TOP = 44.906;
const LAT_BOTTOM = 44.765;
const LON_CENTER = 37.360;

// Проекция равнопромежуточная с поправкой на широту. На 44.8° градус долготы
// короче градуса широты почти на треть, и без поправки Анапа вышла бы
// растянутой вдоль берега.
const LAT_MID = 44.836;
const M_PER_LAT = 110574;
const M_PER_LON = 111320 * Math.cos((LAT_MID * Math.PI) / 180);

/**
 * Холст считается сразу в пикселях отрисовки, а не в условных единицах.
 *
 * Так пришлось сделать из-за качества картинки. Подложка — это <img> с SVG:
 * браузер растрирует её один раз по размеру в разметке, и увеличение через
 * transform растягивает уже готовый растр. При камере, стоявшей на 5.56, карта
 * выходила мыльной, а на больших окнах часть плитки просто не успевала
 * прорисоваться и оставалась серой.
 *
 * Поэтому единицы карты умножены на этот множитель, а увеличение на остановке
 * стало единицей: подложка рисуется в натуральную величину и никогда не
 * растягивается — камера теперь только уменьшает, а уменьшение растр не портит.
 */
const RENDER = 5.56;

// Рисунок карты: 300 × 436 в единицах файла, пропорция 0.688 — это ширина
// брендовой половины (43% от кадра 16:10).
export const MAP_W = 300 * RENDER;
export const MAP_H = 436 * RENDER;

// Запас земли вокруг рисунка: в файле поле шириной 80 единиц со всех сторон, и
// камера ходит по этому полю. Без запаса у краёв из-под карты вылезала полоса
// фона страницы. Число обязано совпадать с рамкой в anapa.svg.
export const MAP_PAD = 80 * RENDER;

const HEIGHT_M = (LAT_TOP - LAT_BOTTOM) * M_PER_LAT;
const WIDTH_M = HEIGHT_M * 0.688;
const LON_LEFT = LON_CENTER - WIDTH_M / M_PER_LON / 2;

/**
 * Границы, по которым ходит камера. Шире рисунка: земля в файле залита с
 * запасом со всех сторон, и камера ездит по этому запасу. Без упора в края
 * при отдалении из-под карты вылезал фон страницы.
 */
export const BOUNDS = {
  minX: -70 * RENDER,
  maxX: 370 * RENDER,
  minY: -70 * RENDER,
  maxY: 506 * RENDER
};

/** Широта и долгота — в координаты холста. */
export function project(lat, lng) {
  return {
    x: ((lng - LON_LEFT) * M_PER_LON / WIDTH_M) * MAP_W,
    y: ((LAT_TOP - lat) * M_PER_LAT / HEIGHT_M) * MAP_H
  };
}

/**
 * Увеличение камеры. Оно одно на всё: отдаление на дальних перегонах было и
 * убрано — скачущий масштаб на экране входа отвлекает сильнее, чем длинный
 * проезд.
 *
 * Раньше здесь стояла единица, чтобы подложка-картинка не растягивалась и не
 * мылилась. Теперь подложка встроена разметкой и остаётся вектором при любом
 * увеличении, поэтому число выбирается по делу: при единице в кадр попадало
 * шесть километров — весь город разом, мелко и неразборчиво.
 *
 * Всё, что нарисовано в единицах холста и должно сохранять экранный размер —
 * метки и толщина линии маршрута, — делится на это число.
 */
export const ZOOM_NEAR = 2.4;

/**
 * Положение холста, при котором точка (x, y) выходит в кадр.
 *
 * По вертикали цель стоит выше середины: снизу лежит карточка филиала, и
 * метка, выведенная точно в центр, оказывалась ровно под ней.
 */
export function cameraTransform(x, y, zoom, width, height) {
  let tx = width / 2 - zoom * x;
  let ty = height * 0.4 - zoom * y;
  tx = Math.min(-zoom * BOUNDS.minX, Math.max(width - zoom * BOUNDS.maxX, tx));
  ty = Math.min(-zoom * BOUNDS.minY, Math.max(height - zoom * BOUNDS.maxY, ty));
  return `translate(${tx}px, ${ty}px) scale(${zoom})`;
}
