// Правило замочков при сбросе, общее для карточки сотрудника и для серверного
// массового сброса (backend/services/executorSettingsReset.js — логика там та же,
// общего модуля у бэка и фронта нет).
//
// Переносы из «Сводки» — премия или переплата, отложенная на следующий месяц —
// приходят с одноразовым замком: `locked` + `carryOnce`. Обычный замок вечный, и
// такая запись пережила бы не только сброс перед «своим» месяцем, но и все
// следующие: премию начислили бы повторно, пока замок не снимут руками. Поэтому
// одноразовый замок сброс снимает: запись остаётся и уходит в зарплату текущего
// месяца, а удалит её уже следующий сброс.
export function keepLockedItems(items) {
  return (items || []).filter(it => it?.locked === true).map(it => {
    if (it.carryOnce !== true) return it;
    const { carryOnce, ...rest } = it;
    return { ...rest, locked: false };
  });
}

// Замок, поставленный руками, всегда обычный: если человек трогает замочек у
// перенесённой записи, одноразовость снимается, дальше она живёт по общим правилам.
export function toggleItemLock(item) {
  const { carryOnce, ...rest } = item;
  return { ...rest, locked: !item.locked };
}
