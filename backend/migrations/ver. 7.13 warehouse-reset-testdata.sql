-- ─────────────────────────────────────────────────────────────────────────────
-- ver. 7.13 — ЗАЧИСТКА ТЕСТОВЫХ ДАННЫХ СКЛАДА
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Модуль складского учёта поехал на боевой сервер раньше, чем в него завели
-- настоящие данные, и всё, что там накопилось за время проверок — операции,
-- инвентаризации, карточки из первых разборов ведомости, — это следы пробных
-- прогонов. Ставить на них настоящий учёт нельзя: инвентарные номера уже выданы
-- несуществующим предметам, а остатки не сходятся ни с чем.
--
-- ── ЧТО ОСТАЁТСЯ ─────────────────────────────────────────────────────────────
--
-- Топология. Она размечена руками, и повторить эту работу дорого:
--
--   warehouse_buildings     корпуса
--   warehouse_floors        этажи вместе с габаритами и контуром плана
--   warehouse_floor_shapes  отрисованные стены, коридоры, подписи
--   warehouse_rooms         кабинеты вместе с полигоном на плане (поле plan)
--   warehouse_storages      места хранения внутри кабинетов
--   warehouse_departments   отделения и коды специальностей
--   warehouse_specialties   справочник специальностей
--
-- Справочники, которые не про операции:
--
--   warehouse_categories       категории
--   warehouse_item_rules       словарь предметов (ver. 7.13)
--   warehouse_contractors      контрагенты
--   warehouse_user_permissions доступы к модулю
--   warehouse_mail_optouts     отписки от рассылок
--
-- ── ЧТО СНОСИТСЯ ─────────────────────────────────────────────────────────────
--
-- Всё движение и всё, что из него выведено: документы, движения, карточки
-- активов, остатки, партии, номенклатура, инвентаризации, ТО и ремонты, заявки
-- поставщикам, нормы и точки заказа, снимки ведомости с разметкой и
-- размещениями, сохранённые отчёты, лог рассылок, суточная утилизация.
--
-- Номенклатура сносится вместе с остальным СОЗНАТЕЛЬНО: на боевой базе она
-- целиком создана прошлыми разборами ведомости (в ней проставлен osvLineKey),
-- своего в ней нет, а после зачистки её вернёт тот же разбор.
--
-- Счётчики документов и инвентарных номеров обнуляются: иначе первый настоящий
-- приход получит номер ПРХ-000123, и «сто двадцать два документа до него» будут
-- искать до тех пор, пока кто-нибудь не вспомнит про тестовый период.
--
-- ── ПОРЯДОК ──────────────────────────────────────────────────────────────────
--
-- Одним TRUNCATE и намеренно БЕЗ CASCADE. Список таблиц замкнут: ссылок в него
-- извне нет, проверено. Если Postgres всё-таки ругнётся на внешний ключ —
-- значит в схеме появилась таблица, о которой этот список не знает, и молча
-- утащить её за собой (а это и сделал бы CASCADE) хуже, чем остановиться.

BEGIN;

TRUNCATE TABLE
  warehouse_movements,
  warehouse_documents,
  warehouse_asset_files,
  warehouse_assets,
  warehouse_stock,
  warehouse_batches,
  warehouse_nomenclature,
  warehouse_inventory_items,
  warehouse_inventory_sessions,
  warehouse_maintenance_orders,
  warehouse_repairs,
  warehouse_rfq_quotes,
  warehouse_rfq_items,
  warehouse_rfq,
  warehouse_reorder_rules,
  warehouse_consumption_norms,
  warehouse_osv_placements,
  warehouse_osv_mappings,
  warehouse_osv_lines,
  warehouse_osv_imports,
  warehouse_outbox,
  warehouse_utilization_daily,
  warehouse_saved_reports,
  warehouse_mail_log,
  warehouse_doc_counters,
  warehouse_inventory_counters
RESTART IDENTITY;

COMMIT;
