--
-- Токен жил в .env. Это годилось, пока модуль вёл программист; заказчик
-- передаёт его человеку, который в консоль не ходит, а сменить токен придётся —
-- они протухают.
--
-- Отдельной строки под него не нужно: он лёг полем в существующую настройку
-- notif_imobis рядом с именем отправителя, и место в JSONB для него уже есть.
-- Пусто означает «взять IMOBIS_TOKEN из окружения», поэтому то, что настроено
-- на бою, продолжает работать без правок.
--
-- Хранится открытым текстом — так же, как токены ботов в messenger_bots с 7.84:
-- шифрование потребовало бы управления ключом шифрования, а он лёг бы в тот же
-- .env, от которого уходим. Доступ к таблице равен доступу к серверу.
--
-- Ключей Fromni здесь намеренно нет. От неё уходят в пользу собственной
-- отправки, и заводить настройку под то, что сворачивают, значит поддерживать
-- её ради одного переходного периода. Fromni продолжает работать от
-- FROMNI_KEY_* в .env, пока нужна.
