-- Каналы становятся явными: Telegram и MAX порознь, тексты только по каналам,
-- каскад только у события, ключи провайдеров в базе (ver. 8.04).
--
-- Общий смысл правки — убрать из настройки размытые сущности. Их было три, и
-- каждая по-своему мешала:
--
--   • ступень «наши боты» вела сразу в два разных бота, и поднять MAX выше
--     Telegram было нельзя — они шли одним шагом;
--   • «полный текст» уходил в любой канал, для которого не завели свой, то есть
--     один и тот же абзац оказывался и в мессенджере, и в SMS, где он стоит
--     трёх сегментов;
--   • общий каскад описывал доставку «вообще», а доставка бывает только
--     конкретного события: просьбу об отзыве в SMS слать незачем, а отмену
--     визита — обязательно.
--
-- Миграция переносит данные так, чтобы после неё ничего не замолчало: каждый
-- шаблон получает каскад, каждый канал — текст.

-- ── Служебные подразделения ───────────────────────────────────────────────
--
-- В справочнике медцентров рядом с клиниками лежат АУП и «Направители» — это
-- не филиалы, куда ходит пациент, а подразделения для учёта. В настройке
-- оповещений они предлагали завести рассылку туда, где рассылать некому.
--
-- Флаг, а не список имён в коде: справочник правит заказчик, и следующее
-- служебное подразделение не должно требовать правки программы.
ALTER TABLE med_centers ADD COLUMN IF NOT EXISTS "servesPatients" BOOLEAN NOT NULL DEFAULT TRUE;

-- Сеяем только то, что однозначно: АУП — административный персонал,
-- «Направители» — учёт внешних врачей. Остальное заказчик пометит сам, если
-- понадобится: ошибиться в чужом справочнике хуже, чем показать лишнюю строку.
UPDATE med_centers SET "servesPatients" = FALSE WHERE code IN ('aup', 'referrers');

-- ── Telegram и MAX порознь ────────────────────────────────────────────────
--
-- Ступень называлась «bot» и означала «любой наш бот, какой найдётся у этого
-- телефона». Это два разных мессенджера с разной аудиторией, и приоритет между
-- ними — решение заказчика, а не случайность порядка в базе.
--
-- Везде, где каскад сохранён, «bot» разворачивается в две ступени. Порядок
-- Telegram → MAX выбран как прежний по факту: subscriberFor отдавал первую
-- подходящую подписку, а Telegram у нас появился раньше и подписчиков там
-- больше. Переставить их местами — теперь одно движение в интерфейсе.

-- Общая настройка (её вот-вот перестанут читать, но пусть останется связной).
UPDATE settings
   SET value = (
         SELECT jsonb_agg(step ORDER BY ord)
           FROM (
             SELECT CASE WHEN s.step = '"bot"'::jsonb THEN '"telegram"'::jsonb ELSE s.step END AS step,
                    s.ord * 2 AS ord
               FROM jsonb_array_elements(value) WITH ORDINALITY AS s(step, ord)
             UNION ALL
             SELECT '"max"'::jsonb, s.ord * 2 + 1
               FROM jsonb_array_elements(value) WITH ORDINALITY AS s(step, ord)
              WHERE s.step = '"bot"'::jsonb
           ) AS expanded
       )
 WHERE key = 'notif_cascade'
   AND value @> '["bot"]'::jsonb;

-- ── Каскад у каждого события ──────────────────────────────────────────────
--
-- Общий каскад уходит, поэтому каждый шаблон должен получить собственный —
-- иначе после релиза замолчали бы все события сразу. Берём то, что было общим:
-- поведение не меняется, меняется только место, где оно записано.
UPDATE notif_templates t
   SET cascade = COALESCE(
         (SELECT value FROM settings WHERE key = 'notif_cascade'),
         '["telegram", "max", "notify+vk", "sms+webchat"]'::jsonb
       )
 WHERE t.cascade IS NULL;

-- ── Тексты только по каналам ──────────────────────────────────────────────
--
-- Поле text было запасным на все каналы сразу. Раскладываем его по тем каналам,
-- где своего текста нет: после релиза «полного текста» в интерфейсе не будет, и
-- незаполненный канал промолчит, а не уйдёт с чужим абзацем.
--
-- SMS получает text только если у него нет своего короткого варианта — иначе
-- переезд 8.03 был бы затёрт длинным текстом, и один лишний символ стоил бы
-- второго сегмента на всей рассылке.
UPDATE notif_templates
   SET "channelTexts" = "channelTexts"
       || CASE WHEN COALESCE("channelTexts"->>'telegram', '') = ''
               THEN jsonb_build_object('telegram', text) ELSE '{}'::jsonb END
       || CASE WHEN COALESCE("channelTexts"->>'max', '') = ''
               THEN jsonb_build_object('max', text) ELSE '{}'::jsonb END
       || CASE WHEN COALESCE("channelTexts"->>'sms', '') = ''
               THEN jsonb_build_object('sms', COALESCE(NULLIF("smsText", ''), text)) ELSE '{}'::jsonb END
       -- Notify — канал у Fromni, по длине он ближе к мессенджеру, чем к SMS:
       -- сегментов там нет. Поэтому ему достаётся полный текст, а не короткий.
       -- Без этой строки ступень Notify осталась бы без текста и молча
       -- пропускалась бы при каждой отправке.
       || CASE WHEN COALESCE("channelTexts"->>'notify', '') = ''
               THEN jsonb_build_object('notify', text) ELSE '{}'::jsonb END
 WHERE text IS NOT NULL AND text <> '';

-- Колонка становится необязательной: заполнять её больше нечем и незачем.
-- Не удаляем — на неё смотрит старый отправщик, который перезапускают руками,
-- и до перезапуска он должен продолжать работать.
ALTER TABLE notif_templates ALTER COLUMN text DROP NOT NULL;

