-- ver. 6.51 — Кнопки действий в сообщениях бота
--
-- Заявки с сайта приходят в рабочий чат текстом, и дальше сотрудник руками
-- переносит те же данные в МИС или в реестр справок. Кнопка под сообщением
-- убирает этот перенос: «Создать пациента» дёргает метод МИС прямо из чата,
-- «Внести в реестр справок» открывает страницу реестра с уже заполненной формой.
--
-- Хранится списком в самом сообщении, а не отдельной таблицей: кнопки живут
-- ровно столько же, сколько сообщение, и всегда читаются вместе с ним —
-- отдельная таблица дала бы join на каждой загрузке чата и ничего больше.
--
-- Формат элемента:
--   {
--     "id":    "mis-create-patient",        -- какой обработчик вызывать (services/messageActions.js)
--     "kind":  "api" | "link",              -- выполнить на сервере или открыть страницу
--     "label": "Создать пациента в МИС",
--     "url":   "/explorer/...",             -- только для kind = link
--     "submissionId": "<uuid>"              -- заявка, из которой брать данные
--   }
--
-- Состояния у кнопки нет: что заявку уже взяли, видно по 👍 — его ставит сервер
-- от нажавшего (routes/chat.js).
ALTER TABLE messages ADD COLUMN IF NOT EXISTS actions JSONB NOT NULL DEFAULT '[]'::jsonb;
