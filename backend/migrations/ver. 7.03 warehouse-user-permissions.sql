-- Права складского модуля: строка на пользователя вместо матрицы должностей.
--
-- До этого права модуля выдавались ролям портала (roles.permissions.warehouse.roles),
-- а внутри модуля жила своя матрица из одиннадцати должностей. Настройка шла через
-- два справочника, и ни один не отвечал на прямой вопрос «что откроет Иванова».
-- Теперь права выставляются человеку в дереве прав админки, как в зарплатном модуле.
--
-- Данные не переносятся: на момент выката права модуля никому не выдавались,
-- модуль готовился к релизу. Доступ остаётся у администраторов портала — им
-- полный набор выдаётся в коде (services/warehouse/permissions.js), без строки
-- в этой таблице.

CREATE TABLE IF NOT EXISTS warehouse_user_permissions (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  "userId"       UUID NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  -- Ключ права → 'block' | 'read' | 'edit'. Перечень ключей в
  -- services/warehouse/permissions.js, там же и проверка входящих значений:
  -- CHECK по содержимому JSONB пришлось бы править вместе с каждым новым отчётом.
  perms          JSONB NOT NULL DEFAULT '{}'::jsonb,
  -- Пустой массив = вся сеть. См. комментарий у модели: пустое ограничение и
  -- отсутствие ограничения в интерфейсе выглядят одинаково.
  "medCenterIds" JSONB NOT NULL DEFAULT '[]'::jsonb,
  "createdAt"    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  "updatedAt"    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Ищут всегда по пользователю; уникальный индекс по "userId" создаётся вместе с
-- UNIQUE выше, отдельный не нужен.

-- Прежняя ветка прав в ролях портала больше не читается. Не удаляем её здесь
-- намеренно: если понадобится вернуться, роли останутся с прежними настройками,
-- а мусорный ключ в JSONB ничего не стоит.
