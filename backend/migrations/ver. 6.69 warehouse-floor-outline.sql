-- ver. 6.69 — контур этажа произвольной формы и доработка технических помещений.
--
-- В ver. 6.68 этаж описывался только габаритами planWidthM × planHeightM, то есть
-- всегда был прямоугольником. Реальные корпуса такими не бывают: Г-образные крылья,
-- срезанные углы, атриумы. Прямоугольная подложка заставляла обводить кабинеты
-- «внутри воображаемой рамки», и план перестал бы соответствовать зданию.
--
-- Габариты остаются: они задают систему координат холста (в метрах), в которой
-- живут и контур, и кабинеты. Контур — это то, что рисуется как стены здания
-- внутри этого холста.
--
-- Миграция аддитивна и идемпотентна: существующие планы продолжают работать, у них
-- outline пустой, и клиент рисует прямоугольник по габаритам, как раньше.

BEGIN;

ALTER TABLE warehouse_floors
  ADD COLUMN IF NOT EXISTS outline JSONB NOT NULL DEFAULT '{}';

COMMENT ON COLUMN warehouse_floors.outline IS
  'Контур этажа в метрах: {"points":[[x,y],…]}. Пустой объект — этаж прямоугольный '
  'по planWidthM × planHeightM (поведение до ver. 6.69). Габариты при непустом '
  'контуре остаются размером холста: контур должен в него укладываться';

-- Технические помещения (коридоры, лестницы, санузлы, серверные) — это фигуры
-- warehouse_floor_shapes, а не кабинеты: инвентаря в них нет, и заводить под
-- коридор кабинет с материально ответственным лицом было бы искажением учёта.
--
-- Но у фигуры не было двух вещей, без которых её нельзя вести из интерфейса:
-- порядка сортировки в списке и площади. Площадь считает клиент по геометрии, а
-- вот собственное имя фигуры нужно хранить — «Коридор» и «Коридор западного
-- крыла» на плане различаются только подписью.
ALTER TABLE warehouse_floor_shapes
  ADD COLUMN IF NOT EXISTS "sortOrder" INTEGER NOT NULL DEFAULT 100,
  ADD COLUMN IF NOT EXISTS "isTechnical" BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN warehouse_floor_shapes."isTechnical" IS
  'Техническое помещение (коридор, лестница, санузел) — участвует в площади этажа, '
  'но не в учёте. FALSE — чисто оформительская фигура: подпись, стена, штриховка';

-- Список видов фигур расширен: в ver. 6.68 их было семь, и на реальном плане не
-- хватало санузлов, серверных и лифтовых холлов. Проверка не ограничением, а
-- комментарием: набор ещё будет пополняться, и ALTER TABLE на каждый новый вид
-- технического помещения — плохая цена за валидацию справочного поля.
COMMENT ON COLUMN warehouse_floor_shapes.kind IS
  'corridor | hall | stairs | elevator | wc | server | utility | wardrobe | '
  'reception_area | wall | door | window | text | area';

CREATE INDEX IF NOT EXISTS warehouse_floor_shapes_floor_z_idx
  ON warehouse_floor_shapes ("floorId", z);

COMMIT;
