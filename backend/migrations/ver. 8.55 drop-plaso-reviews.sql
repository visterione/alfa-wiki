-- Отключение площадки Plaso.pro (ver. 8.55).
--
-- Plaso.pro приезжала в наши доски через GetLoyalty вместе с остальными
-- агрегаторами, но отзывы оттуда к сети отношения почти не имеют: площадка
-- отдаёт чужие карточки и чужих врачей. Для обработчика это был обычный
-- негатив — его читали, назначали ответственного и выясняли, что выяснять
-- нечего; в статистике по площадкам эти отзывы считались нашими и портили и
-- долю негатива, и среднюю оценку. Ответить на такой отзыв через GetLoyalty
-- всё равно нельзя: площадка в списке тех, кому отправка ответа не
-- поддерживается, с самого начала.
--
-- В коде площадка уже отсечена: адаптер GetLoyalty не берёт источники с
-- identity = plasopro, поэтому новых отзывов не будет и без этой миграции.
-- Здесь убирается то, что в коде не лежит, — накопленный архив и сама строка
-- площадки, из-за которой она осталась бы в фильтрах и в разрезе статистики
-- пустым, но видимым пунктом.
--
-- ОТМЕНИТЬ НЕЛЬЗЯ. Отзывы удаляются физически, вместе с историей обработки, и
-- мягкое удаление здесь не используется намеренно: строка с deletedAt так и
-- продолжала бы держать площадку в справочнике. Сделайте резервную копию базы
-- до применения (npm run backup из backend).

BEGIN;

-- Оценка визита из бота (ver. 8.49) заводит карточку отзыва на доске и хранит
-- ссылку на неё. Оценок с площадки Plaso.pro быть не может — их источник наш
-- собственный бот, — но ссылка обнуляется прежде удаления, чтобы миграция не
-- зависела от того, есть ли на связи внешний ключ и с каким он ON DELETE.
DO $$
BEGIN
  IF to_regclass('public.notif_visit_ratings') IS NOT NULL THEN
    UPDATE notif_visit_ratings
       SET "reviewId" = NULL
     WHERE "reviewId" IN (
       SELECT r.id FROM reviews r
        WHERE r."platformId" IN (SELECT id FROM review_platforms WHERE name = 'Plaso.pro')
     );
  END IF;
END $$;

-- История обработки. Удаляется явно, а не полагаясь на CASCADE: связь заведена
-- в Sequelize, а в боевой базе таблицы старше части этих объявлений.
DELETE FROM review_history
 WHERE "reviewId" IN (
   SELECT r.id FROM reviews r
    WHERE r."platformId" IN (SELECT id FROM review_platforms WHERE name = 'Plaso.pro')
 );

-- Сами отзывы, включая уже помеченные удалёнными и уже уехавшие в архив.
DELETE FROM reviews
 WHERE "platformId" IN (SELECT id FROM review_platforms WHERE name = 'Plaso.pro');

-- Строка справочника. Обработчик /api/reviews/platforms/:id в таком случае
-- всего лишь снимает isActive, потому что за площадкой обычно остаются отзывы;
-- здесь их уже нет, и площадку можно убрать совсем.
DELETE FROM review_platforms WHERE name = 'Plaso.pro';

COMMIT;
