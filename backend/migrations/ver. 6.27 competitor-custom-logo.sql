-- ver. 6.27 — Свой логотип клиники-конкурента
--
-- Значок парсер снимает с сайта, но снять его удаётся не всегда: у части
-- клиник на странице нет ни og:image, ни внятной картинки в шапке, и строка
-- в таблице остаётся без опознавательного знака навсегда — повлиять на это
-- из интерфейса было нечем.
--
-- Признак нужен именно отдельным полем, а не догадкой по logoUrl: ночная
-- синхронизация перекачивает значок, как только на сайте меняется адрес
-- картинки (competitorPricesSync.syncLogo), и без явной пометки затирала бы
-- вручную загруженный файл при первом же прогоне.

ALTER TABLE competitor_sources
  ADD COLUMN IF NOT EXISTS "logoIsCustom" BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN competitor_sources."logoIsCustom" IS
  'Логотип загружен человеком — автосбор с сайта его не трогает';
