-- Старший оператор линии: право на архив (ver. 8.10).
--
-- Архив закрытых обращений — это чтение чужих разговоров с пациентами задним
-- числом. Нужен он для разбора спорных ситуаций, то есть считанным людям, а до
-- сих пор лежал третьей вкладкой у всей смены. Признак на связи «линия —
-- сотрудник», а не на пользователе: старший в своём филиале остаётся рядовым
-- оператором в соседнем, и право на архив едет вместе с линией.
--
-- Умолчание false осознанное: после миграции архив пропадает у всех, включая
-- тех, кто им пользовался. Назначить старших надо руками — «Открытая линия и
-- оповещения» → «Линии» → в составе звёздочка у сотрудника. Иначе архив не
-- увидит никто, кроме администраторов портала.
ALTER TABLE omni_line_operators ADD COLUMN IF NOT EXISTS "isSenior" BOOLEAN NOT NULL DEFAULT FALSE;
