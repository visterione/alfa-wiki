-- Вакансии: зарплата и многострочное описание (ver. 8.35).
--
-- ЗАРПЛАТА. До этой версии её указывали внутри описания свободным текстом, и
-- это единственное, что кандидат ищет глазами в первую очередь, — а находил он
-- его в разном виде и в разном месте каждой вакансии. Теперь это отдельное
-- поле.
--
-- Разложено на вид и две суммы, а не хранится строкой, которую набрал админ.
-- Строкой было бы проще ровно один раз — в момент ввода. Дальше начинается:
-- «100 тыс», «100000р», «от 100 до 120», «100 000 — 120 000 руб.» — и это в
-- пределах одной сети и одной недели. Вид фиксирует, о чём речь, а как это
-- написать словами, решает код, поэтому во всех вакансиях, в списке филиала и
-- на странице отклика зарплата выглядит одинаково.
--
--   none        — не указывать (поведение до этой версии)
--   exact       — фиксированная, берётся salaryFrom
--   range       — вилка, salaryFrom … salaryTo
--   negotiable  — договорная, суммы не заполняются
--
-- Валюты и периода («в месяц», «за смену») здесь нет намеренно: сеть платит в
-- рублях, а период у врача, медсестры и администратора разный, и заводить под
-- него пятый вариант ради подписи не стоит — если он важен, его пишут в
-- условиях рядом.
--
-- Зарплата есть только у вакансии, но не у шаблона. Шаблон — это заготовка
-- должности на всю сеть, а платят в филиалах по-разному; шаблон с зашитой
-- суммой пришлось бы править после каждого создания вакансии.
--
-- ОПИСАНИЕ. Колонка description уже TEXT, менять её не нужно — правка целиком
-- в интерфейсе: поле стало многострочным, переносы сохраняются и показываются
-- кандидату. Миграция про это только упоминает, чтобы в истории было видно, с
-- какой версией изменилось поведение.

ALTER TABLE vac_vacancies
  ADD COLUMN IF NOT EXISTS "salaryKind" VARCHAR(12) NOT NULL DEFAULT 'none',
  ADD COLUMN IF NOT EXISTS "salaryFrom" INTEGER,
  ADD COLUMN IF NOT EXISTS "salaryTo"   INTEGER;

-- Проверка держит пару «вид ↔ суммы» согласованной на уровне базы, а не только
-- в маршруте: вилка без верхней границы и точная сумма без суммы — это не
-- «частично заполнено», а состояние, которое нечем показать.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'vac_vacancies_salary_chk'
  ) THEN
    ALTER TABLE vac_vacancies
      ADD CONSTRAINT vac_vacancies_salary_chk CHECK (
        ("salaryKind" = 'none'       AND "salaryFrom" IS NULL AND "salaryTo" IS NULL)
     OR ("salaryKind" = 'negotiable' AND "salaryFrom" IS NULL AND "salaryTo" IS NULL)
     OR ("salaryKind" = 'exact'      AND "salaryFrom" IS NOT NULL AND "salaryFrom" > 0 AND "salaryTo" IS NULL)
     OR ("salaryKind" = 'range'      AND "salaryFrom" IS NOT NULL AND "salaryTo" IS NOT NULL
                                      AND "salaryFrom" > 0 AND "salaryTo" > "salaryFrom")
      );
  END IF;
END $$;
