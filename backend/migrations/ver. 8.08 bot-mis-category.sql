-- Категория подписчика в МИС — у бота, а не у платформы (ver. 8.08).
--
-- Пометка подписчика в карточке пациента задумывалась ещё в 7.84: человек
-- нажимает «поделиться контактом», мы находим его карту по телефону и вешаем на
-- неё категорию. Категорий тогда предполагалось две — «Telegram» и «MAX», и
-- лежали они в .env (MIS_CATEGORY_TELEGRAM, MIS_CATEGORY_MAX). Обе так и
-- остались пустыми, то есть пометка не проставилась ни разу: tagInMis выходил
-- на первой же строке, а подписчик оставался в статусе identified.
--
-- Сеть тем временем завела категории иначе — на каждого бота: не «пришёл из
-- Telegram», а «пришёл из Telegram-бота Альфа Дети». Это и правильнее: карточка
-- пациента должна отвечать, из какого медцентра человек, а не только каким
-- мессенджером он пользуется. Две переменные окружения такого не выражают,
-- поэтому категория переезжает к боту — туда же, где уже лежат его токен,
-- филиал и линия.
--
-- Пусто — бот не помечает никого. Так остаются проверочные боты (organization =
-- 'test'), которым нечего делать в карточках живых пациентов, и боевые, пока
-- категорию для них не завели в МИС.
ALTER TABLE messenger_bots ADD COLUMN IF NOT EXISTS "misCategoryId" INTEGER;
