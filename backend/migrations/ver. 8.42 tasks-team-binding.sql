-- Привязка задачи к команде (ver. 8.42).
--
-- До этого релиза видимость названий задач считалась только по людям: свои
-- задачи, задачи подчинённых по команде и поставленные самим. Из-за этого
-- участник команды не видел, чем заняты сокомандники, и вопрос «кто за что
-- отвечает» внутри команды не имел ответа в интерфейсе.
--
-- Открывать всё подряд нельзя: правило «по людям» появилось не случайно, а
-- после того, как личная задача одного человека другому оказалась на доске у
-- четверых посторонних. Поэтому видимость даёт не совместное участие в
-- команде, а ЯВНАЯ привязка задачи к ней. Командная задача открыта всему
-- составу целиком, включая описание и вложения; задача без команды остаётся
-- личной и живёт по прежнему правилу.
--
-- Существующие задачи не привязываются ни к чему: teamId у них остаётся NULL,
-- то есть все они остаются личными. Это сознательное решение — раздать их по
-- командам задним числом значило бы открыть участникам переписку и файлы за
-- всё время работы модуля, о чём их никто не предупреждал.
--
-- ON DELETE SET NULL, а не CASCADE: удаление команды не должно уносить задачи.
-- Это обещание уже дано в интерфейсе — «Задачи и календари участников не
-- изменятся» в подтверждении удаления команды. Задачи распущенной команды
-- становятся личными.

BEGIN;

ALTER TABLE tasks
  ADD COLUMN IF NOT EXISTS "teamId" uuid
  REFERENCES task_teams(id) ON DELETE SET NULL;

COMMENT ON COLUMN tasks."teamId" IS
  'Команда, которой открыта задача целиком. NULL — личная задача, видна автору, исполнителям и руководителю над исполнителем';

-- Выборка «задачи моих команд» идёт на каждом открытии доски и страницы
-- команды, и без индекса это seq scan по всей таблице задач.
CREATE INDEX IF NOT EXISTS tasks_team_id ON tasks ("teamId");

COMMIT;
