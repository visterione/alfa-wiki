-- Права на вкладки статистики (ver. 9.17).
--
-- Галочки вкладок статистики в карточке пользователя были, а хранить их было
-- негде: столбца не существовало, сервер поле молча отбрасывал, страница его не
-- спрашивала. Права выглядели настроенными и ни на что не влияли.
--
-- Пустой объект — «всё открыто»: отсутствующий ключ читается как разрешение.
-- Поэтому миграция никому ничего не закрывает, и до первой снятой галочки
-- статистика у всех выглядит как раньше.
ALTER TABLE users ADD COLUMN IF NOT EXISTS "statisticsTabs" JSONB NOT NULL DEFAULT '{}'::jsonb;
