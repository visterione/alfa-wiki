-- Ширина колонки channel в журнале отправок (ver. 8.02).
--
-- Колонка заведена в 7.86 как VARCHAR(20), когда каналом была одна ступень:
-- 'telegram', 'max', 'sms'. В 7.94–7.95 у провайдеров появился собственный
-- каскад — несколько ступеней уходят одним запросом, и в channel стал
-- записываться весь маршрут через «→»:
--
--   sender.js:199   route.map(r => `imobis:${r.channel}`).join('→')
--   sender.js:221   sent.channel  (у Fromni — channels.map(c => c.name).join('→'))
--
-- В двадцать символов это перестало помещаться, причём на каскаде по умолчанию:
--
--   notify+vk→sms+webchat              21 символ   ← каскад из DEFAULT_CASCADE
--   imobis:vk→imobis:viber→imobis:sms  33 символа
--
-- Чем это оборачивалось. Postgres на такую запись отвечает отказом
-- (22001 value too long), падает не отправка, а item.update() после неё:
-- сообщение пациенту уже ушло, но строка очереди осталась в состоянии
-- 'pending'. Следующий проход отправщика брал её снова и отправлял ещё раз —
-- и так на каждом проходе, пока человек не пожалуется. Дедупликация тут не
-- спасает: dedup_key защищает от повторного ЗАВЕДЕНИЯ события, а не от
-- повторной отправки уже заведённого.
--
-- Незаметным это оставалось потому, что вторая ступень каскада на бою выключена
-- предохранителем NOTIFIER_ALLOW_FROMNI: до Fromni дело просто не доходило, и
-- всё, что писалось в channel, было именами наших ботов в восемь символов.
-- Нашлось при разборе журнала для вкладки «Боты».
--
-- 64 с запасом: самый длинный мыслимый маршрут сегодня — 33 символа, и место
-- под ещё пару ступеней стоит здесь ничего.
ALTER TABLE notif_outbox ALTER COLUMN channel TYPE VARCHAR(64);
