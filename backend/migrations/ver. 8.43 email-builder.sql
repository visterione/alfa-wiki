-- Конструктор писем и отписка от рассылок (ver. 8.43).
--
-- До этого релиза письмо существовало в базе только как строка HTML. Такую
-- строку нельзя открыть на правку: вёрстка письма — это таблицы с инлайновыми
-- стилями, разобрать их обратно на «заголовок, картинку и кнопку» нельзя. Из-за
-- этого «повторить рассылку» означало повторить её ровно как есть, а любая
-- правка уводила человека во внешний конструктор и обратно с новым кодом.
--
-- Колонка design хранит документ конструктора — то, из чего письмо собрано.
-- HTML остаётся рядом и становится результатом рендера: он нужен для истории
-- (что именно ушло людям) и для старого режима «вставить готовый код». Там, где
-- design пуст, письмо приехало готовым HTML — так и работали все рассылки до
-- этого релиза, и ни одна из них не меняется.
--
-- Таблица email_optouts появилась в этом же релизе не за компанию. Рассылки
-- выходят на пациентов, то есть на внешние адреса, а там отписка — условие
-- доставки: Gmail с 2024 года требует от отправителей свыше 5000 писем в сутки
-- работающую отписку в один клик и иначе роняет в спам весь домен, а не
-- отдельное письмо.
--
-- Ключ таблицы — адрес, а не пользователь. Пациента в Users нет и не будет,
-- его адрес приезжает файлом, и связать отказ с будущей рассылкой можно только
-- по самому адресу. Отказы сотрудников лежат здесь же: правило одно на всех.

BEGIN;

ALTER TABLE email_logs
  ADD COLUMN IF NOT EXISTS "design" jsonb;

COMMENT ON COLUMN email_logs."design" IS
  'Документ конструктора писем (ver. 8.43). NULL — письмо отправлено готовым HTML';

ALTER TABLE email_templates
  ADD COLUMN IF NOT EXISTS "design" jsonb;

COMMENT ON COLUMN email_templates."design" IS
  'Документ конструктора писем (ver. 8.43). NULL — шаблон хранит готовый HTML';

CREATE TABLE IF NOT EXISTS email_optouts (
  email      varchar(320) PRIMARY KEY,
  source     varchar(32)  NOT NULL DEFAULT 'link',
  reason     text,
  "createdAt" timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE email_optouts IS
  'Отказы от почтовых рассылок. Ключ — адрес в нижнем регистре: получатель может не быть пользователем портала';
COMMENT ON COLUMN email_optouts.source IS
  'link — ссылка в подвале письма, oneclick — заголовок List-Unsubscribe, manual — отписали руками в портале';

-- Сохранённые модули: настроенная секция или блок, который переиспользуют в
-- других письмах. Шапку с логотипом и подвал с контактами собирают один раз, а
-- вставляют в каждую рассылку — без этого конструктор заставляет собирать их
-- заново, и через месяц в сети три разных «фирменных» подвала.
--
-- Хранится кусок документа конструктора, а не HTML: модуль должен вставляться
-- в письмо живым и правиться дальше, а не приезжать неразбираемой вёрсткой.
--
-- Модули общие для тех, у кого есть право на анонсы. Личных нет намеренно:
-- смысл модуля ровно в том, чтобы фирменный блок был один на всех.
CREATE TABLE IF NOT EXISTS email_modules (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name        varchar(200) NOT NULL,
  kind        varchar(16)  NOT NULL DEFAULT 'section',
  payload     jsonb        NOT NULL,
  "createdBy" uuid         NOT NULL,
  "createdAt" timestamptz  NOT NULL DEFAULT now(),
  "updatedAt" timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS email_modules_kind_idx ON email_modules (kind);

COMMENT ON TABLE email_modules IS
  'Сохранённые модули конструктора писем: готовая секция или блок для переиспользования';
COMMENT ON COLUMN email_modules.kind IS
  'section — целая секция с колонками, block — отдельный блок';
COMMENT ON COLUMN email_modules.payload IS
  'Кусок документа конструктора: секция или блок целиком';

COMMIT;
