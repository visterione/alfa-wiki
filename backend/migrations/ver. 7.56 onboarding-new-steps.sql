-- ver. 7.56 — два новых шага онбординга: «Проверка отделом кадров» (hr_check) и
-- «Карточка врача» (doctor_card). Заодно прежний шаг website сменил название на
-- «Реклама» — это только заголовок в коде, базы он не касается.
--
-- Схему менять не нужно: шаги описаны в коде (services/onboarding/process.js), а
-- назначения — строки в onb_assignments с текстовым stepKey. Миграция нужна
-- ровно из-за одного: чек-лист готовности собирается из шагов, и заявки,
-- запущенные до выката, без задач по новым шагам никогда не дошли бы до
-- «Запущен» — пункты остались бы вечно незакрытыми, а открыть их было бы нечем.
--
-- Статусы у двух шагов разные, потому что разное место в процессе:
--
--   • hr_check идёт от согласования, параллельно созданию учётки, — значит
--     задача нужна всем заявкам в работе: и согласованным, и заведённым в МИС.
--
--   • doctor_card открывается после создания учётки, вместе с расписанием,
--     бейджем и рекламой. Согласованным заявкам его поставит сам движок, когда
--     закроется шаг учётки, — им подставлять задачу руками не нужно и вредно:
--     она появилась бы раньше, чем врач заведён. Поэтому только mis_created.
--
-- Уже запущенные (launched) не трогаем ни тем, ни другим: их процесс закончен, а
-- новые открытые задачи только выдали бы людям список врачей, которые давно
-- принимают. Черновики, анкеты на согласовании и доработке пропускаем — им всё
-- поставит согласование главврача.
--
-- Исполнителей не подставляем: назначений по новым шагам ещё нет. Задачи
-- остаются открытыми с пустым assigneeIds, а когда администратор укажет людей в
-- настройках раздела, PUT /api/onboarding/settings/:stepKey пересчитает
-- исполнителей у всех открытых задач шага — включая эти.
--
-- Срок отсчитываем от выката, а не от согласования: до сегодняшнего дня шагов не
-- существовало, и просрочка «с прошлого месяца» была бы ложной. Двое суток —
-- календарный запас к 16 и 24 рабочим часам из process.js.
--
-- Миграция идемпотентна: повторную задачу ловит уникальный индекс
-- onb_tasks_app_step_uniq.

INSERT INTO onb_tasks ("applicationId", "stepKey", "assigneeIds", "dueAt")
SELECT a.id, 'hr_check', '[]'::jsonb, NOW() + INTERVAL '2 days'
  FROM onb_applications a
 WHERE a.status IN ('approved', 'mis_created')
ON CONFLICT ("applicationId", "stepKey") DO NOTHING;

INSERT INTO onb_tasks ("applicationId", "stepKey", "assigneeIds", "dueAt")
SELECT a.id, 'doctor_card', '[]'::jsonb, NOW() + INTERVAL '2 days'
  FROM onb_applications a
 WHERE a.status = 'mis_created'
ON CONFLICT ("applicationId", "stepKey") DO NOTHING;
