-- ver. 8.38 — возврат работы кандидату с шага проверки.
--
-- До этого вернуть анкету умел только шаг решения, и только пока процесс не
-- начался. Документы на трудоустройство кандидат присылает уже после
-- согласования, и проверяющему (юристу) нужно то же самое: «вот это поправьте».
--
-- Замечания лежат у той задачи, которую переоткрыли: { note, fields, by, at,
-- count }. Сам признак «умеет возвращать» — в процессе вакансии (JSONB),
-- колонки не требует.
ALTER TABLE vac_tasks ADD COLUMN IF NOT EXISTS returned JSONB;

COMMENT ON COLUMN vac_tasks.returned IS
  'Возврат кандидату: { note, fields: [], by, at, count }. Пусто — задачу не возвращали.';
