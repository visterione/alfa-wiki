-- Заготовки текстов для лабораторных уведомлений (ver. 7.93).
--
-- Отдельной миграцией, а не правкой 7.88: та уже уехала в релиз, и по имени
-- файла должно быть видно, с каким изменением приехала строка в базе.
--
-- Состав подстановок известен из самой Renovatio: на её экране лабораторных
-- уведомлений предлагаются только ФИО, имя, кабинет, организация и клиника с
-- адресом и телефоном. Ничего про сами анализы — ни номера заказа, ни перечня
-- исследований. То есть сообщение по смыслу общее, и всё нужное для него у нас
-- уже есть в подстановках.
--
-- Тексты заведены ВЫКЛЮЧЕННЫМИ: разбор события от МИС ещё не написан — мы не
-- видели ни одного живого запроса и не знаем, чем оно опознаёт пациента.
-- Включённый шаблон создавал бы впечатление работающего уведомления.

INSERT INTO notif_templates (event, text, "withConfirm", "isActive")
SELECT * FROM (VALUES
  ('lab_full',
   'Здравствуйте, {{имя}}! Результаты ваших анализов готовы. Забрать их можно в регистратуре {{клиника}} или в личном кабинете.',
   FALSE, FALSE),
  ('lab_partial',
   'Здравствуйте, {{имя}}! Часть результатов ваших анализов готова, их уже можно забрать в {{клиника}}. Об остальных сообщим отдельно.',
   FALSE, FALSE)
) AS labs(event, text, "withConfirm", "isActive")
WHERE NOT EXISTS (SELECT 1 FROM notif_templates WHERE event IN ('lab_full', 'lab_partial'));
