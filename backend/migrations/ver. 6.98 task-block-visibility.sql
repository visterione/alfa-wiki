BEGIN;

-- Блоки задач в календаре: «занято, без названия» вместо «видно команде».
--
-- Задача, поставленная в план, превращается в блок времени, и до этой версии
-- блок создавался с уровнем видимости team. Уровень честно означает «название
-- видно тем, с кем человек состоит в общей команде» — то есть любой сокомандник
-- мог получить название чужой задачи, запросив событие по идентификатору.
--
-- Коллеге нужно знать, что время занято, а чем именно — дело исполнителя и его
-- руководителя, и для этого есть модуль «Задачи» со своим правилом видимости
-- (services/tasks/teams.js, taskScope). Новые блоки с ver. 6.97 создаются с
-- уровнем busy; эта миграция приводит к нему уже созданные.
--
-- Трогаются только блоки задач и только уровень team: личные события (private,
-- busy) и то, что человек открыл сам (public, shared), остаются как есть.
UPDATE calendar_events
SET visibility = 'busy'
WHERE "taskPartId" IS NOT NULL
  AND visibility = 'team';

COMMIT;
