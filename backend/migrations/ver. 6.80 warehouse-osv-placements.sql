-- ver. 6.80 — размещение позиций ведомости по кабинетам.
--
-- ── Что было сломано ─────────────────────────────────────────────────────────
--
-- До сих пор кабинет задавался ветке дерева 1С: одна ветка — один кабинет
-- (ver. 6.73). На реальных данных сети это неверно, и неверно не в мелочах.
-- Под веткой «Кабинет Хирурга» лежит имущество пяти-шести физических кабинетов
-- хирургического отделения, а кабинетов в сети около сотни. Ни ветка, ни даже
-- отдельная строка не отвечают на вопрос «где эта вещь стоит»: строка «Стул
-- СТ 6 серый, 3 шт» — это три стула, и они могут стоять в трёх разных местах.
--
-- То есть человек, добросовестно разметивший все 54 ветки, получал формально
-- разобранную ведомость с неверным размещением. Это хуже, чем медленно.
--
-- ── Что меняется ─────────────────────────────────────────────────────────────
--
-- Размещение становится собственной сущностью: «из этой строки ведомости N
-- единиц лежат в этом кабинете». Одна строка раскладывается на сколько угодно
-- кабинетов, остаток нераспределённого виден всегда.
--
-- ── Почему карточка создаётся при размещении, а не до него ───────────────────
--
-- Инвентарный номер содержит код специальности отделения на момент постановки
-- на учёт и потом не меняется никогда (services/warehouse/numbering.js). Создать
-- карточку раньше, чем известен кабинет, значит выдать ей код АХО навсегда — а
-- это три тысячи карточек с неверным номером, и исправить их нельзя по
-- определению номера.
--
-- Поэтому материализация идёт ПО РАЗМЕЩЕНИЯМ: пока строка не размещена, карточки
-- нет, а когда размещена — номер выдаётся сразу правильный. Побочный эффект
-- приятный: разбор перестаёт быть операцией «всё или ничего». Кабинеты можно
-- заводить и наполнять по частям, разными людьми и в разные дни, а не держать
-- всю ведомость нерасразобранной, пока не размечена последняя ветка.
--
-- ── Почему старый путь остался ───────────────────────────────────────────────
--
-- Кабинет у ветки никуда не делся и работает как запасной: если у строки нет ни
-- одного размещения, берётся кабинет её ветки, как раньше. Во-первых, это не
-- ломает 3173 карточки, уже созданные по ver. 6.73. Во-вторых, бывают ветки,
-- которые честно соответствуют одному кабинету, и заставлять раскладывать их
-- поштучно было бы работой без содержания.
--
-- Миграция аддитивна и идемпотентна.

BEGIN;

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. РАЗМЕЩЕНИЯ
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS warehouse_osv_placements (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  account     VARCHAR(20) NOT NULL,

  -- Ключ строки ведомости, а не ссылка на строку снимка: снимки сменяются
  -- каждый месяц, а размещение переживает их все. Ключ устойчив между
  -- выгрузками (ver. 6.72), и это ровно то, что здесь нужно.
  "lineKey"   VARCHAR(40) NOT NULL,

  "roomId"    UUID NOT NULL REFERENCES warehouse_rooms(id) ON UPDATE CASCADE ON DELETE CASCADE,
  -- Место хранения внутри кабинета — уточнение, а не обязанность. Требовать
  -- выбирать полку для каждой из тысяч позиций значит не разложить ничего;
  -- пустое поле означает «первое место хранения этого кабинета».
  "storageId" UUID REFERENCES warehouse_storages(id) ON UPDATE CASCADE ON DELETE SET NULL,

  quantity    NUMERIC(14,3) NOT NULL,
  note        TEXT,
  "placedBy"  UUID REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE warehouse_osv_placements
  DROP CONSTRAINT IF EXISTS warehouse_osv_placements_qty_chk;
ALTER TABLE warehouse_osv_placements
  ADD CONSTRAINT warehouse_osv_placements_qty_chk CHECK (quantity > 0);

-- Одна запись на пару «строка + кабинет»: положить в один кабинет дважды — это
-- не два размещения, а одно с большим количеством. Иначе остаток пришлось бы
-- собирать суммированием, а убрать лишнее стало бы неоднозначно.
CREATE UNIQUE INDEX IF NOT EXISTS warehouse_osv_placements_uniq
  ON warehouse_osv_placements (account, "lineKey", "roomId");

CREATE INDEX IF NOT EXISTS warehouse_osv_placements_room_idx
  ON warehouse_osv_placements ("roomId");

COMMENT ON TABLE warehouse_osv_placements IS
  'Сколько единиц строки ведомости лежит в каком кабинете. Одна строка раскладывается на несколько кабинетов';
COMMENT ON COLUMN warehouse_osv_placements."storageId" IS
  'Уточнение внутри кабинета; NULL — первое место хранения кабинета';

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. ОБРАТНАЯ ССЫЛКА У КАРТОЧКИ
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Идемпотентность повторного разбора раньше держалась на счёте карточек по
-- osvLineKey. С размещениями этого мало: карточек у строки столько же, но
-- разложены они по кабинетам, и считать их по кабинету нельзя — актив могли
-- переместить документом, и тогда счёт по месту дал бы «не хватает» и создал
-- дубли. Ссылка на размещение от переездов не зависит.
ALTER TABLE warehouse_assets
  ADD COLUMN IF NOT EXISTS "osvPlacementId" UUID
    REFERENCES warehouse_osv_placements(id) ON UPDATE CASCADE ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS warehouse_assets_osv_placement_idx
  ON warehouse_assets ("osvPlacementId") WHERE "osvPlacementId" IS NOT NULL;

COMMENT ON COLUMN warehouse_assets."osvPlacementId" IS
  'Размещение, из которого создана карточка; по нему повторный разбор узнаёт, что она уже есть';

COMMIT;
