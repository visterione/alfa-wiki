-- Опись по нескольким кабинетам сразу.
--
-- До ver. 7.36 область описи была из двух крайностей: один кабинет или всё
-- отделение целиком. Реальный приказ почти всегда посередине — «кабинеты 305,
-- 307 и 310», три из восьми в отделении. Такую опись приходилось заводить
-- тремя отдельными, а комиссия по одному приказу подписывала три документа,
-- и расхождения считались порознь по каждому.
--
-- Отделение остаётся отдельной областью, а не превращается в список кабинетов:
-- оно накрывает и те кабинеты, которые появятся в нём завтра, — именно этого от
-- описи по отделению и ждут.
--
-- Список, а не таблица связи: он читается и пишется только целиком, вместе с
-- самой описью, и запросов «в каких описях был этот кабинет» в модуле нет.
--
-- BEGIN/COMMIT здесь нет намеренно: файл применяется скриптом
-- scripts/migrateInventoryMultiRoom.js, и транзакцию открывает он — вложенный
-- BEGIN внутри уже открытой транзакции Postgres принимает с предупреждением, а
-- COMMIT из файла закрыл бы транзакцию раньше самого скрипта. Тем, кто применяет
-- файл через psql, нужен флаг -1 (весь файл одной транзакцией).

ALTER TABLE warehouse_inventory_sessions
  ADD COLUMN IF NOT EXISTS "roomIds" JSONB NOT NULL DEFAULT '[]'::jsonb;

-- Уже существующие описи по одному кабинету: список делаем таким же, как у
-- новых, чтобы код читал одно поле, а не два по признаку scope.
UPDATE warehouse_inventory_sessions
   SET "roomIds" = jsonb_build_array("roomId")
 WHERE "roomId" IS NOT NULL
   AND "roomIds" = '[]'::jsonb;
