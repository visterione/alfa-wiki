-- GetLoyalty отключён (ver. 8.84).
--
-- Отзывы с площадок собирает и отвечает на них Альфа Парсер (8.80). Проверка
-- на бою прошла, и заказчик убрал GetLoyalty целиком. Отзывы, пришедшие через
-- него, остаются как были — с externalId gl_… и ответами в syncMeta; уходят
-- только настройки подключения.
--
-- review_sync_configs удаляется, а не очищается: в ней логины и пароли
-- кабинета GetLoyalty открытым текстом (credentials JSONB), держать их без
-- надобности незачем. Отменить нельзя — таблицу пришлось бы заводить заново,
-- а пароли вписывать руками.

DROP TABLE IF EXISTS review_sync_configs;

-- Список площадок, снятых с GetLoyalty на время перехода. Без самого
-- GetLoyalty он ничего не значит.
DELETE FROM settings WHERE key = 'reviews.getloyalty.excludedPlatforms';

-- Отзыв из одной оценки больше не получает заглушку вместо текста: она
-- читалась как текст отзыва и попадала в отчёты и уведомления. Старые
-- заглушки убираем тоже, иначе на доске жили бы два вида пустого отзыва.
UPDATE reviews SET "reviewText" = '' WHERE "reviewText" = '(текст отсутствует)';
