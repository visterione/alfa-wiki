-- Отметка прочтения в открытой линии (ver. 8.27).
--
-- Список обращений отвечал на вопрос «что у меня есть», но не отвечал на
-- «где у меня новое»: строка показывала последнюю реплику и время, и оператор
-- с десятком взятых чатов различал их только по порядку сортировки. Реплика
-- пациента, пришедшая в четвёртый сверху чат, ничем себя не выдавала.
--
-- Одна отметка на переписку, а не журнал продвижений курсора, как в мессенджере
-- (ver. 8.26): там несколько участников и вопрос «кто и во сколько прочитал»
-- осмысленный, здесь у обращения ровно один исполнитель. Непрочитанное — это
-- входящие позже отметки.

ALTER TABLE omni_conversations
  ADD COLUMN IF NOT EXISTS "operatorReadAt" TIMESTAMP WITH TIME ZONE;

-- Засев: всё, что уже кем-то взято, считаем прочитанным на момент выката.
-- Иначе в первый же день у каждого оператора загорится вся его переписка за
-- всё время — сигнал, который ничего не значит и который поэтому перестанут
-- замечать раньше, чем он начнёт работать.
--
-- Очередь и архив не трогаем намеренно: ничьё обращение и так помечено в
-- списке как новое, а закрытое не читают.
UPDATE omni_conversations
   SET "operatorReadAt" = NOW()
 WHERE "operatorReadAt" IS NULL
   AND status = 'assigned';
