-- Все страницы редактора и html-страницы — доступны для печати (ver. 9.03).
--
-- В 8.99 флаг появился выключенным у всех, чтобы автор сам решал, что
-- печатать. Страниц оказалось слишком много, чтобы отмечать их по одной, и
-- заказчик выбрал обратный путь: включить всем, а исключить единичные
-- (html-приложения, от которых на бумаге остаётся пустая оболочка) вручную.
-- Разовое действие: повторный запуск снова включит и то, что успели
-- выключить руками, поэтому после отбора его не запускать.

UPDATE pages
   SET "isPrintable" = true
 WHERE "contentType" IN ('wysiwyg', 'html')
   AND "isPrintable" = false;
