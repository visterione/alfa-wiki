-- Поиск по переписке на триграммах.
--
-- Оба поиска — по одному чату и по всем чатам сразу — ищут подстроку через
-- ILIKE '%…%'. Такому условию обычный B-tree бесполезен, и до ver. 7.31 каждый
-- запрос в строку поиска означал последовательный проход по всей таблице
-- сообщений. У глобального поиска к тому же ещё и по attachments::text.
--
-- GIN на триграммах — единственный индекс, который умеет ускорять именно
-- подстроку, причём без правки самих запросов: планировщик подхватывает его
-- сам. Полнотекстовый tsvector здесь не подошёл бы: он ищет слова целиком, а
-- в чате ищут «фамилию, кусок номера, часть названия файла».
--
-- Запросы короче трёх символов индексу не по зубам (триграмма — три символа),
-- такие по-прежнему идут перебором. На это и рассчитано: клиенты не ищут,
-- пока не набрано хотя бы два-три символа.
--
-- CONCURRENTLY: строятся эти индексы на боевой таблице сообщений долго, и
-- обычный CREATE INDEX запер бы на это время всю переписку.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE INDEX CONCURRENTLY IF NOT EXISTS messages_content_trgm_idx
  ON messages USING gin (content gin_trgm_ops);

CREATE INDEX CONCURRENTLY IF NOT EXISTS messages_attachments_trgm_idx
  ON messages USING gin ((attachments::text) gin_trgm_ops);
