-- ver. 6.65 — Артикулы услуг лаборатории в позициях сравнения
--
-- Лист лабораторий собирается по коду 804н: одна строка — одна услуга,
-- колонки — лаборатории. Артикул при этом терялся, хотя у каждой лаборатории
-- он свой: у кода A09.05.042 это ALFA03-001 у «Альфа», Проф-02-002
-- у «Альфа Проф» и 8 у «Инвитро». Для файла импорта в МИС артикул —
-- единственный обязательный ключ обновления, без него прайс не поправить.
--
-- Формат:
--   {
--     "CL-LAB": [
--       { "code": "CL-0142", "serviceId": 6232, "title": "Аланинаминотрансфераза",
--         "categoryPath": "Анализы Альфа / Лаборатория МЦ / Биохимия крови" }
--     ]
--   }
--
-- Массив, а не одна запись, — намеренно: у одного кода 804н в одной
-- лаборатории бывает несколько артикулов (обычная услуга и профосмотровая
-- с другой ценой). Такие позиции выгрузка пропускает и показывает списком,
-- а чтобы их показать, надо знать, что их несколько.
ALTER TABLE price_comparison_items
  ADD COLUMN IF NOT EXISTS "misRefs" JSONB NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN price_comparison_items."misRefs" IS
  'Услуги МИС за колонкой листа: {"CL-LAB": [{code, serviceId, title, categoryPath}]}. '
  'Заполняется при добавлении услуг и при сборке файла импорта';

-- Заполнять задним числом нечем: артикулы приходят из МИС, а не из БД.
-- Существующие листы получат их при первой же сборке файла импорта —
-- она читает прейскурант МИС и сохраняет найденное сюда.
