-- Склады медцентра: «Склад», «Ремонт» и то, что заведут после них.
--
-- Модуль исходил из того, что всё имущество разложено по кабинетам до нуля. На
-- первых же реальных данных это оказалось неверным: есть резерв на замену, есть
-- то, что уехало в ремонт, есть материалы, которые просто лежат на складе и ни
-- к какому кабинету не относятся. Раскладывать их «куда-нибудь» значит соврать
-- в учёте, а не раскладывать — держать очередь размещения вечно непустой.
--
-- Почему это кабинет, а не новая сущность: весь модуль завязан на roomId —
-- остатки через место хранения, карточки активов, движения (fromRoomId/toRoomId),
-- опись, зона ответственности МОЛ, все отчёты. Отдельная таблица потребовала бы
-- продублировать каждый из этих путей и разошлась бы с ними на первой же
-- нестандартной операции.
--
-- Отличий от кабинета ровно два, и оба следуют из отсутствия физического
-- помещения: этажа у склада нет (floorId остаётся пустым, на плане он не
-- рисуется) и в аналитику посещаемости он не входит — склад не принимает
-- пациентов, и его ноль приёмов испортил бы средние по сети.
--
-- Общие на весь медцентр, а не на этаж: резерв в сети один, и делить его по
-- этажам значило бы выдумывать границу, которой в жизни нет. Между медцентрами
-- склады не общие — имущество принадлежит своему юрлицу и своему МОЛ.
--
-- Сами склады заводит скрипт scripts/migrateWarehouseServicePlaces.js: каждому
-- нужен публичный токен для QR (его считает код, а не SQL) и место хранения,
-- иначе положить в него материал будет некуда.
--
-- BEGIN/COMMIT здесь нет намеренно: файл применяется скриптом, и транзакцию
-- открывает он. Тем, кто применяет файл через psql, нужен флаг -1.

ALTER TABLE warehouse_rooms
  ADD COLUMN IF NOT EXISTS "isService" BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS "serviceKind" VARCHAR(20);

-- serviceKind отдельно от isService, потому что вопросы разные. isService — «это
-- склад, а не кабинет»: без этажа, вне аналитики, отдельной группой в списках.
-- serviceKind — «к нему ведёт быстрое действие»: кнопка «На склад» и уход в
-- ремонт должны найти ровно одно место своего медцентра. У складов, которые
-- заведут руками сверх этих двух, serviceKind пуст: они полноценные места
-- хранения, просто без своей кнопки.
CREATE UNIQUE INDEX IF NOT EXISTS warehouse_rooms_service_kind_uniq
    ON warehouse_rooms ("medCenterId", "serviceKind")
 WHERE "serviceKind" IS NOT NULL AND "isActive" = TRUE;
