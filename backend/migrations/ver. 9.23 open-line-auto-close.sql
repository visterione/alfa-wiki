-- Автозакрытие обращений после тишины (ver. 9.23).
--
-- Разговор, в котором уже давно никто не пишет — ни пациент, ни оператор, —
-- висел в «Моих» и в очереди, пока его не закроют руками. Закрывать его
-- забывали: последняя реплика «спасибо, до свидания» не требует ответа, и
-- обращение оставалось открытым неделями, путая счётчики и показатели.
--
-- Срок — свой у каждой линии, в часах. 0 — не закрывать. По умолчанию 8: так
-- заказчик решил включить это сразу на всех линиях.

ALTER TABLE omni_lines ADD COLUMN IF NOT EXISTS "autoCloseHours" INTEGER NOT NULL DEFAULT 8;
