-- Этаж принадлежит медцентру напрямую: корпуса убраны из работы.
--
-- Уровень корпуса завели по ТЗ, и на бумаге он выглядел безобидно. На реальных
-- пользователях оказалось, что спуск «медцентр → корпус → этаж → кабинет»
-- никто не проходит: сотрудник знает, что он на четвёртом этаже, а в каком
-- корпусе — вопрос, на который он отвечает не всегда. Лишний уровень стоит
-- одного нажатия на каждом выборе кабинета и ничего не сообщает.
--
-- ── Что здесь происходит и чего здесь НЕТ ────────────────────────────────────
--
-- Этажу добавляется собственный medCenterId, заполненный из его корпуса.
-- buildingId остаётся на месте и становится необязательным: по нему видно, из
-- какого корпуса этаж пришёл, и восстановить прежнюю структуру можно в любой
-- момент.
--
-- Таблица warehouse_buildings НЕ удаляется и НЕ гасится. Удалять её нельзя ещё
-- и технически: связь «корпус → этажи» объявлена с ON DELETE CASCADE, и
-- удаление корпуса унесло бы этажи вместе с планами, контурами и полигонами
-- кабинетов.
--
-- Этажи НЕ объединяются. У медцентра может оказаться два четвёртых этажа — из
-- административного и из главного корпуса, — и слить их автоматически нельзя:
-- у каждого свой план, свой контур и свои полигоны кабинетов в одних и тех же
-- координатах. Это решение владельца данных: он переносит кабинеты руками
-- (кабинету теперь можно сменить этаж) и удаляет опустевший этаж сам.
--
-- Чтобы два одинаковых этажа можно было различить в списке, пустое название
-- заполняется названием корпуса — но только там, где корпусов у медцентра
-- больше одного. Там, где корпус один, «4 этаж» и так однозначен, а приписка к
-- нему была бы шумом.
--
-- BEGIN/COMMIT здесь нет намеренно: файл применяется скриптом, и транзакцию
-- открывает он. Тем, кто применяет файл через psql, нужен флаг -1.

ALTER TABLE warehouse_floors
  ADD COLUMN IF NOT EXISTS "medCenterId" UUID REFERENCES med_centers(id)
    ON UPDATE CASCADE ON DELETE RESTRICT;

UPDATE warehouse_floors f
   SET "medCenterId" = b."medCenterId"
  FROM warehouse_buildings b
 WHERE b.id = f."buildingId"
   AND f."medCenterId" IS NULL;

-- Название корпуса переезжает в название этажа там, где без него два этажа
-- медцентра выглядели бы одинаково.
UPDATE warehouse_floors f
   SET name = b.name
  FROM warehouse_buildings b
 WHERE b.id = f."buildingId"
   AND (f.name IS NULL OR btrim(f.name) = '')
   AND (SELECT count(*) FROM warehouse_buildings b2
         WHERE b2."medCenterId" = b."medCenterId" AND b2."isActive" = TRUE) > 1;

ALTER TABLE warehouse_floors ALTER COLUMN "buildingId" DROP NOT NULL;

-- Этажи медцентра ищут постоянно: дерево локаций, планы, отчёты.
CREATE INDEX IF NOT EXISTS warehouse_floors_medcenter_idx
    ON warehouse_floors ("medCenterId");
