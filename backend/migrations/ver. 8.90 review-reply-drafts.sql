-- Черновики ответов на отзывы (ver. 8.90).
--
-- Альфа Парсер пишет локальной моделью два-три варианта ответа на свежий
-- отзыв; в карточке они — подсказки, отправляет ответ по-прежнему человек.
-- Сами черновики лежат в reviews."syncMeta".drafts и живут, только пока
-- отзыв ждёт ответа: после ответа они удаляются сразу, остальное (архив,
-- удалённые с площадки, пролежавшие месяц) — ночной уборкой. Отдельная
-- таблица под то, что почти всегда недолговечно, не нужна.
--
-- Миграция только разрешает новый вид задачи парсера — «черновики».
-- Отменить можно, если в очереди не осталось задач этого вида.

ALTER TABLE review_collector_jobs DROP CONSTRAINT IF EXISTS review_collector_jobs_kind_check;
ALTER TABLE review_collector_jobs ADD CONSTRAINT review_collector_jobs_kind_check
  CHECK (kind IN ('reply', 'check', 'complaint', 'input', 'draft'));
