-- Время просмотра сообщения собеседником (ver. 8.26).
--
-- Галочки в мессенджере были, а ответа на вопрос «когда он это прочитал» не
-- было: в chat_members лежит одна отметка lastReadAt, и она всё время
-- обновляется. По ней видно, что сообщение прочитано, но у сообщения недельной
-- давности она показала бы сегодняшнее утро — то есть время открытия чата, а
-- не момент, когда человек увидел именно это сообщение.
--
-- Журнал хранит историю продвижений курсора. Время просмотра сообщения — это
-- самая ранняя отметка участника, которая не раньше момента отправки.
--
-- Почему журнал курсора, а не строка на каждую пару (сообщение, участник):
-- курсор двигается один раз на всю прочитанную пачку, поэтому в группе из
-- десяти человек одна строка заменяет десятки, а после ночи молчания одна
-- строка накрывает всю утреннюю переписку.
--
-- readAt — одновременно момент прочтения и граница курсора: маршрут чтения
-- ставит lastReadAt = now(), то есть «я вижу всё, что было до этой секунды».
-- Две колонки врали бы о точности, которой здесь нет.

CREATE TABLE IF NOT EXISTS chat_read_marks (
  "chatId" UUID NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
  "userId" UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "readAt" TIMESTAMP WITH TIME ZONE NOT NULL,
  PRIMARY KEY ("chatId", "userId", "readAt")
);

-- Выборка всегда одна и та же: отметки чата начиная с даты самого старого
-- загруженного сообщения
CREATE INDEX IF NOT EXISTS chat_read_marks_chat_read_idx
  ON chat_read_marks ("chatId", "readAt");

-- Засеваем журнал текущими курсорами. Без этого вся уже прочитанная переписка
-- в день выката осталась бы без единой галочки: клиент считает прочтение по
-- журналу, и пустой журнал он прочёл бы как «никто ничего не читал».
--
-- Время у засеянных отметок приблизительное — это момент последнего открытия
-- чата, а не просмотра каждого сообщения. Честнее показать его, чем потерять
-- сам факт прочтения; для сообщений, отправленных после выката, время уже
-- точное.
INSERT INTO chat_read_marks ("chatId", "userId", "readAt")
SELECT "chatId", "userId", "lastReadAt"
FROM chat_members
WHERE "lastReadAt" IS NOT NULL
ON CONFLICT DO NOTHING;
