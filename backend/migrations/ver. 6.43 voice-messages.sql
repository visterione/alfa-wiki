-- ver. 6.43 — Голосовые сообщения
--
-- Тип сообщения расширяется значением 'voice'. Отдельный тип, а не 'file'
-- с признаком внутри attachments, потому что от типа зависит вся отрисовка:
-- голосовое показывается плеером, а не строкой «файл 42 КБ», и в списке чатов
-- превью у него своё.
--
-- Значение ENUM в Postgres добавляется только так — пересоздавать тип нельзя,
-- на нём висит колонка messages.type с данными. IF NOT EXISTS делает миграцию
-- повторяемой.
--
-- Имя типа сгенерировал Sequelize при первом создании таблицы: enum_<таблица>_<колонка>.
ALTER TYPE enum_messages_type ADD VALUE IF NOT EXISTS 'voice';

-- Длительность и прочие метаданные голосового лежат в messages.attachments
-- (JSONB), отдельных колонок не заводим:
--   [{ "kind": "voice", "path": "uploads/chat-attachments/...m4a",
--      "mimeType": "audio/mp4", "size": 12345, "duration": 7.4 }]
--
-- Волна в интерфейсе декоративная — набор столбиков, детерминированно
-- выведенный из id сообщения. Она одинакова на всех клиентах, но со звуком
-- не связана. Настоящие пики потребовали бы разбора аудио при загрузке и
-- своей колонки; договорились, что это не нужно.
