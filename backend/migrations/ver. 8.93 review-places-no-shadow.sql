-- Места площадок без «Сверки» (ver. 8.93).
--
-- Сверка отзывов парсера с карточками GetLoyalty нужна была, пока отзывы
-- шли из двух источников. GetLoyalty удалён в 8.84, и на странице «Площадки»
-- переключатель режимов убран: выбранный медцентр теперь и есть включение
-- места. Места, оставшиеся в сверке с медцентром, переводим в работу —
-- иначе они молча не заводили бы карточки, хотя в интерфейсе выглядят
-- включёнными. Лавины карточек не будет: парсер заводит их только отзывам
-- не старше двух недель, остальные лишь связываются с уже заведёнными.
--
-- Режим shadow в ограничении таблицы остаётся: вернуть его можно запросом,
-- если сверка когда-нибудь снова понадобится.

UPDATE review_platform_places
   SET mode = 'live', "updatedAt" = NOW()
 WHERE mode = 'shadow' AND "boardId" IS NOT NULL;
