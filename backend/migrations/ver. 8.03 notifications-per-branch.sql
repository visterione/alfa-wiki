-- Почва под раздельные филиалы: тексты по каналам, каскад на событие,
-- настройки на филиал (ver. 8.03).
--
-- До сих пор оповещения были устроены как одна сеть с одним голосом: один текст
-- на событие, один каскад на всё, одни тихие часы. Пока клиника была одна, это
-- было честным упрощением. Теперь их шесть, у каждой свои боты, свой лицевой
-- счёт у провайдера и, что важнее, свои привычки: детская пишет иначе, чем
-- стоматология, а SMS с адресом филиала бессмысленна, если филиал в тексте не
-- назван.
--
-- Миграция ничего не переключает: все три новые вещи необязательны, пусто в них
-- означает «как было». Переезд филиалов делается потом и по одному.

-- ── Тексты по каналам ─────────────────────────────────────────────────────
--
-- Было два поля: text (в мессенджеры) и smsText (в SMS). Деление по длине, а не
-- по каналу, и этого перестало хватать: у Telegram есть разметка и кнопки, у
-- MAX своя длина строки, у SMS — сегменты по 70 символов кириллицей. Один текст
-- «для мессенджеров» на два разных мессенджера — это компромисс, который не
-- нужен, раз оба наши.
--
-- JSONB, а не три колонки: ступени каскада — открытый список, и следующий канал
-- не должен требовать миграции. Ключ совпадает с именем канала в journal
-- (telegram, max, sms), пустое значение или отсутствие ключа означает «взять
-- text», как и раньше. Поэтому существующие шаблоны продолжают работать без
-- единой правки.
ALTER TABLE notif_templates ADD COLUMN IF NOT EXISTS "channelTexts" JSONB NOT NULL DEFAULT '{}'::jsonb;

-- Прежний smsText переезжает в общий вид. Колонку не удаляем: отправщик и
-- админка правятся в этом же релизе, но старый процесс notifier в tmux
-- перезапускают руками, и до перезапуска он должен продолжать работать.
UPDATE notif_templates
   SET "channelTexts" = jsonb_build_object('sms', "smsText")
 WHERE "smsText" IS NOT NULL AND "smsText" <> ''
   AND ("channelTexts" IS NULL OR "channelTexts" = '{}'::jsonb);

-- Готовые тексты едут в очередь вместе со строкой, а не достаются из шаблона в
-- момент отправки. Так уже сделано с text и smsText, и по той же причине: между
-- заведением события и отправкой проходят часы (напоминание — сутки), шаблон за
-- это время могут поправить, и человек получил бы не тот текст, который был
-- обещан на момент записи.
ALTER TABLE notif_outbox ADD COLUMN IF NOT EXISTS "channelTexts" JSONB NOT NULL DEFAULT '{}'::jsonb;

-- ── Каскад на событие ─────────────────────────────────────────────────────
--
-- Общий каскад на все события не выдерживает первого же возражения заказчика:
-- просьбу оценить приём нет смысла слать по SMS — по SMS её не выполнить,
-- кнопок там нет, а деньги списываются. Такое событие должно жить только в
-- ботах и молчать, если человек на них не подписан.
--
-- NULL — идти общим каскадом. Свой список ступеней — идти им.
ALTER TABLE notif_templates ADD COLUMN IF NOT EXISTS cascade JSONB;

-- ── Настройки филиала ─────────────────────────────────────────────────────
--
-- Общие настройки остаются там же, где лежали (таблица settings, ключи
-- notif_cascade, notif_quiet_hours, notif_imobis) и служат основанием. Здесь —
-- только отличия конкретного филиала: пустое поле означает «как в общих», и
-- филиал, которому нечего переопределять, строки тут не имеет вовсе.
--
-- Ключ — медцентр из справочника портала, а не organization ботов. У них разный
-- смысл: медцентр — это филиал, куда ходит пациент, organization — лицевой счёт
-- у провайдера, и на один счёт приходится несколько филиалов. Настраивают
-- филиал, поэтому и ключ филиала.
CREATE TABLE IF NOT EXISTS notif_branch_settings (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    "medCenterId" UUID NOT NULL REFERENCES med_centers(id) ON DELETE CASCADE,
    cascade       JSONB,
    "quietHours"  JSONB,
    -- Своё имя отправителя и своя группа: имя проходит модерацию у операторов
    -- связи на конкретное юрлицо, и у филиалов оно закономерно разное.
    imobis        JSONB,
    -- Выключенный филиал не получает оповещений вовсе. Нужно на время переезда:
    -- клинику подключают к нашей рассылке по одной, и остальные в это время
    -- должны продолжать получать их из МИС, а не оба сразу.
    "isEnabled"   BOOLEAN NOT NULL DEFAULT TRUE,
    "createdAt"   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    "updatedAt"   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS notif_branch_settings_uniq ON notif_branch_settings ("medCenterId");

-- Шаблон филиала ищется по (event, medCenterId), общий — по (event, NULL).
-- Без индекса это перебор всей таблицы на каждое событие детектора.
CREATE INDEX IF NOT EXISTS notif_templates_event_branch_idx ON notif_templates (event, "medCenterId");
