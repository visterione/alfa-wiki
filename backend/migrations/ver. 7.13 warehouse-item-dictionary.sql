-- ver. 7.13 — СЛОВАРЬ ПРЕДМЕТОВ ЦЕЛИКОМ
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Механика словаря приехала в ver. 6.79, а наполнение осталось ручным: 32
-- правила, и все со способом учёта 'auto'. С ver. 6.79 'auto' в словаре не
-- значит ничего — цена из классификации убрана, и строка без явного
-- 'asset'/'material' остаётся неразобранной. То есть словарь был, а разбор
-- по-прежнему держался на разметке веток.
--
-- Здесь он заполнен целиком: 645 правил на все 622 ведущих слова августовской
-- выгрузки МЦ.04, покрытие 2992 строк из 2992. Размечать словарь руками больше
-- не нужно ни на этой базе, ни на боевой — миграция ставит одно и то же.
--
-- ── Как принималось решение ──────────────────────────────────────────────────
--
-- Два вопроса разведены так же, как их разводит сам словарь:
--
--   ЧТО ЭТО     — категория, по ведущему слову названия.
--   КАК УЧИТЫВАТЬ — карточкой с инвентарным номером или количеством на полке.
--
-- Карточкой учитываем то, что живёт годами и опознаётся поштучно: медицинское
-- оборудование, оргтехнику, мебель, бытовую и инженерную технику, крупный
-- хозинвентарь. Количеством — всё остальное, и в том числе медицинский
-- ИНСТРУМЕНТ: это решение принято ещё в ver. 6.79 (см. комментарий у модели
-- WhItemRule) и здесь не пересматривается. Инструмент отвечает на вопрос «что
-- это», а не «как учитывать», и щипцы за 15 000 ₽ всё равно лежат в ЦСО
-- пачкой, а не по одной с биркой.
--
-- Выражений всего 23 — ровно там, где общее правило по слову ошибается
-- систематически: «Шкаф коммутационный» это не мебель, «Камера Горяева» не
-- холодильник, «Планшет для ИФА» не Lenovo. Выражение сильнее ведущего слова,
-- поэтому исключение задаётся одной строкой и не ломает общее правило.
--
-- ── Что миграция ПЕРЕЗАПИСЫВАЕТ ──────────────────────────────────────────────
--
-- Совпавшие по паре «выражение + способ поиска» правила обновляются, а не
-- пропускаются. Это сознательно: те 32 правила со способом учёта 'auto'
-- выглядят настроенными, но не классифицируют ничего, и оставить их значило бы
-- оставить 32 дырки в покрытии. Правила, добавленные людьми ПОСЛЕ этой
-- миграции, она не трогает — её запускают один раз.
--
-- Способ учёта и категорию дальше правят в интерфейсе: Склад → Справочники →
-- Словарь предметов. Одно правило — одно решение, разбор перечитывает словарь
-- на каждом запуске.

