-- Счёт Имобиса и источник события принадлежат филиалу (ver. 8.25).
--
-- Два независимых замечания заказчика, но обе правки про одно и то же: сеть —
-- это не одна клиника с оттенками, а шесть медцентров, у каждого свой договор и
-- свой порядок.
--
-- ── Имобис ───────────────────────────────────────────────────────────────
--
-- Учётная запись у Имобиса заведена на каждый медцентр отдельно, и трафик по
-- ним распределён намеренно: SMS всей сети через один лицевой счёт никто не
-- шлёт. Значит, API-ключ — такое же имущество филиала, как токен его бота, а не
-- общая настройка сети с переопределением.
--
-- До 8.25 было наоборот: общая строка settings.notif_imobis держала токен, имя
-- отправителя, группу ВК и песочницу, а филиал мог переопределить только имя и
-- токен. Наследование выглядело удобным ровно до первого вопроса «а с какого
-- счёта ушла эта SMS» — ответа по интерфейсу не было, приходилось помнить,
-- заполнено ли у филиала поле.
--
-- Поэтому общая настройка не просто перестаёт быть основанием, а исчезает:
-- филиал без своего токена теперь не отправляет SMS вовсе и виден
-- предупреждением. Молчаливая отправка с чужого счёта хуже неотправки — за неё
-- платит другое юрлицо, и обнаруживается это счётом в конце месяца.
--
-- Чтобы бой не встал в момент выката, общее значение раскопировано по всем
-- филиалам, принимающим пациентов. Своё у филиала сильнее скопированного.
--
-- ── Источник события ─────────────────────────────────────────────────────
--
-- Оповещения приходят к нам двумя разными путями, и путь зависит от события, а
-- не от филиала целиком:
--
--   • запись, перенос, отмена, напоминание, отзыв — забором: детектор раз в
--     минуту спрашивает getAppointments «что изменилось»;
--   • готовность лабораторных исследований и частичная готовность — вебхуком:
--     МИС зовёт наш адрес сама, потому что спросить её об этом нечем
--     (getPatientLabResults требует patient_key, выдаваемый только по логину
--     пациента).
--
-- Настройки под это не было вовсе: путь был вшит в код — детектор порождал одно,
-- приёмник /api/mis-events записывал другое в журнал и дальше ничего не делал.
-- Теперь это явный выбор на каждую пару «филиал × событие», потому что
-- подключают филиалы по одному, и у половины сети событие может ещё ехать из
-- МИС, пока у другой уже идёт забором.

-- ── Настройка Имобиса переезжает в филиалы ────────────────────────────────
--
-- Своё значение филиала сильнее: в правой части || оно перекрывает
-- скопированное. Словари senders/vkGroups по организациям остались от 7.95 —
-- их содержимое разбирается здесь же и тоже переезжает в филиал.
INSERT INTO notif_branch_settings ("medCenterId", imobis, "createdAt", "updatedAt")
SELECT mc.id,
       jsonb_strip_nulls(jsonb_build_object(
         'token',   NULLIF(s.value->>'token', ''),
         'sender',  COALESCE(
                      NULLIF(s.value->'senders'->>mc."botOrganization", ''),
                      NULLIF(s.value->>'sender', '')
                    ),
         'vkGroup', COALESCE(
                      NULLIF(s.value->'vkGroups'->>mc."botOrganization", ''),
                      NULLIF(s.value->>'vkGroup', '')
                    )::bigint,
         'sandbox', CASE WHEN s.value->>'sandbox' = 'true' THEN TRUE END
       )),
       NOW(), NOW()
  FROM med_centers mc
  CROSS JOIN settings s
 WHERE s.key = 'notif_imobis'
   AND mc."servesPatients" = TRUE
ON CONFLICT ("medCenterId") DO UPDATE
   SET imobis = EXCLUDED.imobis || COALESCE(notif_branch_settings.imobis, '{}'::jsonb),
       "updatedAt" = NOW();

-- Общая настройка не удаляется, а уходит в архив под другим ключом. Удаление
-- было бы необратимым: если копирование выше промахнулось мимо филиала, чей
-- botOrganization не проставлен, восстанавливать токен было бы неоткуда — в
-- .env его с 8.04 может уже не быть.
UPDATE settings
   SET key = 'notif_imobis_archived',
       description = 'Архив: общий счёт Имобиса до ver. 8.25, раскопирован по филиалам'
 WHERE key = 'notif_imobis'
   AND NOT EXISTS (SELECT 1 FROM settings WHERE key = 'notif_imobis_archived');

-- Если архив уже есть (миграцию запустили дважды) — просто убираем исходную.
DELETE FROM settings WHERE key = 'notif_imobis';

-- ── Источник события у филиала ────────────────────────────────────────────
--
-- Объект вида {"created":"poll","lab_full":"webhook"}. NULL и отсутствующий
-- ключ означают «как принято по умолчанию»: лабораторные — вебхуком, остальные
-- — забором. Заполнять строки копией умолчаний незачем: они разъедутся при
-- первой же правке кода, а смысла в такой копии нет.
ALTER TABLE notif_branch_settings ADD COLUMN IF NOT EXISTS "eventSources" JSONB;

-- Событие, пришедшее вебхуком, не привязано к визиту: готовность анализов
-- живёт своей жизнью, appt_id у неё нет. Колонка и так была необязательной —
-- проверяем это явно, потому что теперь на неё рассчитывает приёмник.
ALTER TABLE notif_outbox ALTER COLUMN appt_id DROP NOT NULL;

-- Разбирать принятое событие мы начинаем сразу, поэтому признак «разобрано»
-- перестаёт быть украшением. Индекс под выборку неразобранных уже есть
-- (mis_events (event, processed)) — добавляем только причину отказа, чтобы
-- «пришло, но в очередь не попало» было видно в журнале, а не выяснялось
-- сравнением двух таблиц.
ALTER TABLE mis_events ADD COLUMN IF NOT EXISTS "skipReason" TEXT;
