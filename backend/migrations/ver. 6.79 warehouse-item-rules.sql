-- ver. 6.79 — словарь предметов: чем является позиция ведомости.
--
-- ── Зачем ────────────────────────────────────────────────────────────────────
--
-- До сих пор на все вопросы о позиции отвечало одно число — порог 10 000 ₽
-- (ver. 6.73). Но вопросов два, и они независимы:
--
--   • ЧТО ЭТО за предмет — медицинское оборудование, инструмент, мебель,
--     расходник. Отвечает название.
--   • КАК ЕГО УЧИТЫВАТЬ — карточкой с инвентарным номером или количеством на
--     полке. Отвечает цена за единицу.
--
-- Цена честно отвечает только на второй. На первый она не отвечает в принципе:
-- «Ножницы глазные остроконечн. 113 мм» за 522 ₽ и «Одеяло 145*210» за 1350 ₽
-- по цене неразличимы, а это инструмент и мягкий инвентарь. Проверялось на
-- августовской выгрузке — разделение по стоимости давало ошибку слишком часто,
-- чтобы результат можно было принять без ручного перебора всех 2992 строк.
--
-- ── Почему словарь ведущих слов ──────────────────────────────────────────────
--
-- Первое слово названия в ведомости — это почти всегда тип предмета, и слов
-- этих мало. По августовской выгрузке: 625 разных ведущих слов на 2992 строки,
-- при этом топ-50 слов покрывают 51 % строк, топ-200 — 81 %, топ-300 — 88,5 %.
-- Шкаф — 129 строк, Стол — 103, Щипцы — 89, Тумба — 76, Ножницы — 73,
-- Электрод — 66, Компьютер — 60, Пинцет — 60, Зажим — 58, Кресло — 43.
--
-- Значит размечать нужно не строки, а слова: двести решений вместо трёх тысяч.
-- И, что важнее, словарь переиспользуется — он работает на следующем месяце и
-- на новых медцентрах, тогда как разметка строк умирает при первом
-- переименовании группы в 1С (ключ строки завязан на путь по дереву).
--
-- ── Почему правило не заменяет решение человека ──────────────────────────────
--
-- Словарь встраивается ТРЕТЬИМ звеном: правило по строке → правило ветки →
-- словарь → порог цены. Явно заданное человеком сильнее словаря, а словарь
-- сильнее порога. Порог остаётся последним фолбэком, поэтому при пустом
-- словаре поведение ровно такое же, как до этой миграции — откатывать нечего.
--
-- Миграция аддитивна и идемпотентна.

BEGIN;

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. СЛОВАРЬ
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS warehouse_item_rules (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Что ищем в названии. Для 'head' это ведущее слово в нормальной форме
  -- («шкаф»), для 'contains' — подстрока, для 'regex' — выражение JS.
  pattern        TEXT NOT NULL,
  "matchType"    VARCHAR(10) NOT NULL DEFAULT 'head',

  -- Как учитывать: 'auto' — по цене за единицу (как раньше), 'asset' — всегда
  -- карточкой, 'material' — всегда остатком, 'ignore' — не заводить.
  --
  -- Отдельного вида «инструмент» здесь намеренно нет. Инструмент — это
  -- КАТЕГОРИЯ (что это), а учитывается он количеством, то есть accounting =
  -- 'material'. Заводить третий способ учёта значило бы менять проводки,
  -- остатки и инвентаризацию ради названия; если он однажды понадобится, это
  -- будет смена значения в правиле, а не переделка схемы.
  accounting     VARCHAR(20) NOT NULL DEFAULT 'auto',

  "categoryId"   UUID REFERENCES warehouse_categories(id) ON UPDATE CASCADE ON DELETE SET NULL,
  unit           VARCHAR(20),

  -- Порог для accounting='auto' у этого класса предметов. Инструменту он нужен
  -- другой, чем оргтехнике: щипцы за 15 000 ₽ — всё ещё расходуемый инструмент,
  -- а монитор за 15 000 ₽ — карточка.
  "assetThreshold" NUMERIC(12,2),

  note           TEXT,
  "isActive"     BOOLEAN NOT NULL DEFAULT TRUE,
  "createdBy"    UUID REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL,
  "createdAt"    TIMESTAMPTZ NOT NULL DEFAULT now(),
  "updatedAt"    TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE warehouse_item_rules
  DROP CONSTRAINT IF EXISTS warehouse_item_rules_match_chk;
ALTER TABLE warehouse_item_rules
  ADD CONSTRAINT warehouse_item_rules_match_chk
  CHECK ("matchType" IN ('head', 'contains', 'regex'));

ALTER TABLE warehouse_item_rules
  DROP CONSTRAINT IF EXISTS warehouse_item_rules_accounting_chk;
ALTER TABLE warehouse_item_rules
  ADD CONSTRAINT warehouse_item_rules_accounting_chk
  CHECK (accounting IN ('auto', 'asset', 'material', 'ignore'));

-- Длина выражения ограничена намеренно: регулярное выражение приходит от
-- человека и прогоняется по трём тысячам строк на каждый расчёт разбора.
-- Короткое выражение не гарантирует отсутствие катастрофического отката, но
-- отсекает случайную вставку целого документа в поле.
ALTER TABLE warehouse_item_rules
  DROP CONSTRAINT IF EXISTS warehouse_item_rules_pattern_chk;
ALTER TABLE warehouse_item_rules
  ADD CONSTRAINT warehouse_item_rules_pattern_chk
  CHECK (length(pattern) BETWEEN 1 AND 200);

-- Одно правило на пару «выражение + способ поиска». Регистр не различаем: в
-- ведомости одно и то же слово встречается и «Шкаф», и «ШКАФ».
CREATE UNIQUE INDEX IF NOT EXISTS warehouse_item_rules_pattern_uniq
  ON warehouse_item_rules (lower(pattern), "matchType");

COMMENT ON TABLE warehouse_item_rules IS
  'Словарь предметов: по названию позиции — категория и способ учёта. Третье звено разбора ведомости, после правил строки и ветки';
COMMENT ON COLUMN warehouse_item_rules."matchType" IS
  'head — ведущее слово названия; contains — подстрока; regex — выражение';
COMMENT ON COLUMN warehouse_item_rules.accounting IS
  'auto — по цене за единицу; asset — карточкой; material — остатком; ignore — не заводить';
COMMENT ON COLUMN warehouse_item_rules."assetThreshold" IS
  'Порог цены для accounting=auto у этого класса; NULL — порог ветки, затем общий по модулю';

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. БАЗОВОЕ ДЕРЕВО КАТЕГОРИЙ
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Справочник категорий существует с ver. 6.68, но пуст: заводить его руками при
-- живом разборе некогда, а без него словарю не на что ссылаться и поле
-- «категория» у 3173 карточек остаётся пустым.
--
-- Состав выведен из самой ведомости, а не придуман: это те классы, на которые
-- фактически распадаются её названия.
--
-- ОКОФ, амортизационная группа и срок полезного использования оставлены
-- пустыми СОЗНАТЕЛЬНО. Владелец этих чисел — бухгалтерия (см. комментарий у
-- warehouse_assets."accumulatedDepreciation"), и проставить их правдоподобной
-- догадкой значит получить расхождение с 1С, которое всплывёт при первой
-- сверке и будет выглядеть ошибкой портала. Механика переноса в карточку
-- готова: как только бухгалтерия назовёт значения, они начнут проставляться
-- сами на всех активах категории.

INSERT INTO warehouse_categories (id, name, kind, "sortOrder", "createdAt", "updatedAt")
SELECT gen_random_uuid(), v.name, v.kind, v.ord, now(), now()
FROM (VALUES
  ('Медицинское оборудование',      'fixed',    10),
  ('Медицинский инструмент',        'fixed',    20),
  ('Оргтехника и ИТ',               'fixed',    30),
  ('Мебель',                        'fixed',    40),
  ('Бытовая техника',               'fixed',    50),
  ('Инженерное оборудование',       'fixed',    60),
  ('Хозяйственный инвентарь',       'fixed',    70),
  ('Расходные материалы',           'material', 80),
  ('Лекарственные препараты',       'material', 90),
  ('Текстиль и мягкий инвентарь',   'material', 100),
  ('Хозяйственные материалы',       'material', 110),
  ('Канцелярия',                    'material', 120)
) AS v(name, kind, ord)
WHERE NOT EXISTS (
  SELECT 1 FROM warehouse_categories c WHERE c.name = v.name
);

COMMIT;
