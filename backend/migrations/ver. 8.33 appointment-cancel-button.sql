-- Кнопка «Отменить запись» под напоминанием (ver. 8.33).
--
-- Подтверждение визита из бота работало с 8.03: человек нажимал «Подтверждаю», и
-- отметка уходила в МИС методом confirmAppointment. Обратного действия не было
-- вовсе — отменить визит можно было только звонком в колл-центр.
--
-- Повод к правке — переезд с Fromni. Там в тексте напоминания стояла просьба
-- ответить цифрой: 1 — подтверждаю, 2 — отменяю, 3 — перенести. Разбор ответа и
-- вызов метода Renovatio жили на стороне Fromni, и вместе с ней это уходит.
--
-- Почему кнопки, а не цифры. Ответ цифрой приходит обычным текстом, а всякий
-- текст от подписчика у нас становится обращением в открытую линию — «2» легла
-- бы оператору в очередь вместо отмены визита. Разделить их можно только
-- догадкой: помнить, кому и когда ушло напоминание, и толковать ближайшую цифру
-- как ответ на него. При двух визитах в один день на один семейный номер такая
-- догадка отменяет не тот визит. Кнопка несёт идентификатор визита в себе, и
-- догадываться не о чем.
--
-- Перенос (цифра 3) не делаем совсем: атомарного метода в Renovatio нет, перенос
-- там — это отмена со ссылкой на новый визит плюс создание нового по свободному
-- слоту, то есть полноценная онлайн-запись внутри бота. Просьба перенести
-- остаётся разговором с оператором, для которого открытая линия и заведена.
--
-- Отдельным признаком, а не третьим значением withConfirm: отмена без
-- подтверждения тоже осмысленна, а старая колонка продолжает означать ровно то,
-- что означала.
ALTER TABLE notif_templates ADD COLUMN IF NOT EXISTS "withCancel" BOOLEAN NOT NULL DEFAULT FALSE;

-- Очередь хранит снимок настроек шаблона на момент заведения события: между
-- заведением и отправкой проходят часы, и галку за это время могут снять. Иначе
-- под текстом, обещающим отмену, кнопки бы не оказалось — и наоборот.
ALTER TABLE notif_outbox ADD COLUMN IF NOT EXISTS "withCancel" BOOLEAN NOT NULL DEFAULT FALSE;
