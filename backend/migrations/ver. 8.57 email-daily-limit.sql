-- Суточный предел почтовых рассылок и порции по дням (ver. 8.57).
--
-- Объём рассылок растёт, и главный риск здесь не технический, а репутационный:
-- почтовые службы смотрят не на письмо, а на поведение отправителя. Десять
-- тысяч писем, ушедших с одного домена за час, — ровно та картина, по которой
-- Gmail и Mail.ru принимают решение о домене целиком. Дальше в спам падает всё,
-- включая записи на приём и восстановление пароля.
--
-- Поэтому рассылка, которая не помещается в суточный предел, не отменяется и не
-- режется — она растягивается по дням. Каждый день становится отдельной
-- рассылкой в таблице email_logs: со своим списком получателей, своим статусом
-- и своей отменой. Отдельная таблица под «рассылку из порций» не заводится
-- намеренно: порция — это обычная отложенная рассылка, и весь механизм отправки,
-- отмены и истории у неё уже есть. Новыми нужны только три поля, по которым
-- история собирает порции обратно в одну строку.
--
-- Отменить можно: колонки добавляются пустыми, старые рассылки их не
-- используют, и удаление колонок вернёт таблицу в прежний вид.

ALTER TABLE email_logs ADD COLUMN IF NOT EXISTS "batchId" UUID;
ALTER TABLE email_logs ADD COLUMN IF NOT EXISTS "partIndex" INTEGER;
ALTER TABLE email_logs ADD COLUMN IF NOT EXISTS "partTotal" INTEGER;

COMMENT ON COLUMN email_logs."batchId" IS
  'Общий ключ порций одной рассылки, растянутой по дням. NULL — рассылка уместилась в один день';
COMMENT ON COLUMN email_logs."partIndex" IS 'Номер порции, начиная с 1';
COMMENT ON COLUMN email_logs."partTotal" IS 'Сколько всего порций в рассылке';

-- По batchId история собирает порции в одну строку. Частичный индекс, потому
-- что у подавляющего большинства рассылок колонка пуста: они уходят за день.
CREATE INDEX IF NOT EXISTS email_logs_batch_id_idx
  ON email_logs ("batchId") WHERE "batchId" IS NOT NULL;

-- Суточный предел. Значение по умолчанию — тысяча писем: заметно ниже предела
-- любой почтовой службы (Google Workspace — 2000 внешних получателей в сутки на
-- ящик, Яндекс 360 — 500), но не настолько мало, чтобы рассылка на пять тысяч
-- растянулась на месяц. Настраивается в интерфейсе, код ради этого не трогают.
INSERT INTO settings (key, value, description, "createdAt", "updatedAt")
VALUES (
  'email_daily_limit',
  '{"perDay": 1000}'::jsonb,
  'Сколько писем рассылки уходит за сутки. 0 — без ограничения',
  NOW(), NOW()
)
ON CONFLICT (key) DO NOTHING;
