-- Индекс под постраничную выборку истории чата.
--
-- Страницы истории берутся «от края назад», и до ver. 7.30 курсором была одна
-- лишь метка времени. Сообщения, попавшие в одну миллисекунду (бот вываливает
-- пачку за раз), при этом либо дублировались на стыке страниц, либо терялись.
-- Курсор стал парой (createdAt, id) — и порядок в индексе должен совпадать с
-- порядком выборки, иначе база всё равно уйдёт в сортировку.
--
-- CONCURRENTLY: на боевой таблице сообщений обычный CREATE INDEX держит запись
-- заблокированной, то есть на время построения индекса чат встаёт целиком.
CREATE INDEX CONCURRENTLY IF NOT EXISTS messages_chat_created_id_idx
  ON messages ("chatId", "createdAt" DESC, id DESC);
