-- Длительность задачи и многодневная подзадача (ver. 8.48).
--
-- До этого релиза у задачи не было ни одной даты: даты, оценка и статус жили
-- только в подзадачах, а статус и формат задачи выводились из них. Для мелкой
-- работы этого хватало, но крупная задача с цепочкой подзадач идёт неделю, и
-- сказать это в модуле было нельзя — ни срока задачи, ни периода, ни в
-- карточке, ни в графике.
--
-- Хуже другое: подзадача была запаяна в один день. Оценка сравнивалась с нормой
-- ОДНОГО дня, план создавал ОДИН блок в календаре, plannedDate был одним днём.
-- Подзадача на 20 ч не ставилась в план вообще — приходил 409 «не помещается»,
-- и единственным выходом оставался split, который задумывался как наказание за
-- третий перенос, а не как способ работать с крупным куском.
--
-- Что добавляется и почему именно так.
--
-- tasks."startDate" и tasks."dueDate" — срок задачи: начало и конец. ХРАНЯТСЯ, а
-- не выводятся из подзадач, потому что это договорённость, а не производная:
-- автор сначала говорит «с понедельника по пятницу», и только потом расписывает
-- подзадачи внутрь. Выведенный период (min начала … max срока по подзадачам) в
-- модуле тоже есть, но он отвечает на другой вопрос — «когда это фактически
-- расписано», — и нарушить его нельзя по определению, а срок задачи нарушить
-- можно, и это надо видеть.
--
-- Это ГЛАВНОЕ поле срока в модуле. У простой задачи без подзадач оно и есть её
-- срок: подзадача там одна, неявная, и спрашивать у неё второй срок значило бы
-- задавать один вопрос дважды. Подзадачи со своими сроками появляются только
-- когда работу разбивают, и живут они внутри срока задачи.
--
-- startDate пустой значит «работа на один день» — тот же порядок, что и у
-- подзадач, чтобы правило было одно на весь модуль.
--
-- task_parts."startDate" — начало окна работы. Окно это [startDate..dueDate], и
-- оценка раскладывается по его рабочим дням. NULL означает «один день, как
-- раньше»: поэтому ни одна существующая подзадача не переписывается и не меняет
-- поведения. Обратная запись (startDate = dueDate у всех старых строк) была бы
-- честнее на вид, но сделала бы каждую старую подзадачу «окном в один день» и
-- заставила бы интерфейс рисовать раскладку там, где выбирать нечего.
--
-- task_part_assignees."plannedUntil" — последний день раскладки. Источник
-- правды о раскладке — блоки в календаре, а эти две даты нужны, чтобы список
-- задач и входящие могли написать «в плане 22–25 сент.», не поднимая календарь
-- на каждую строку. plannedDate остаётся первым днём и сохраняет своё главное
-- свойство: NULL значит «лежит во входящих», и на этом держится весь экран
-- входящих.

BEGIN;

ALTER TABLE tasks
  ADD COLUMN IF NOT EXISTS "startDate" date;
ALTER TABLE tasks
  ADD COLUMN IF NOT EXISTS "dueDate" date;

COMMENT ON COLUMN tasks."startDate" IS
  'Первый день работы над задачей. NULL — задача на один день (dueDate)';
COMMENT ON COLUMN tasks."dueDate" IS
  'Срок задачи — договорённость автора. NULL — срока у задачи нет, есть только сроки подзадач';

-- Та же проверка, что и у подзадач: срок, у которого конец раньше начала, ломает
-- всё сразу — от списка рабочих дней до суммы часов, которая никогда не сойдётся.
ALTER TABLE tasks
  DROP CONSTRAINT IF EXISTS tasks_due_order;
ALTER TABLE tasks
  ADD CONSTRAINT tasks_due_order
  CHECK ("startDate" IS NULL OR "dueDate" IS NULL OR "startDate" <= "dueDate");

ALTER TABLE task_parts
  ADD COLUMN IF NOT EXISTS "startDate" date;

COMMENT ON COLUMN task_parts."startDate" IS
  'Начало окна работы. NULL — подзадача на один день (dueDate). Оценка раскладывается по рабочим дням окна';

ALTER TABLE task_part_assignees
  ADD COLUMN IF NOT EXISTS "plannedUntil" date;

COMMENT ON COLUMN task_part_assignees."plannedUntil" IS
  'Последний день раскладки. NULL при заполненном plannedDate — раскладка в один день';

-- Окно, у которого конец раньше начала, ломает всё сразу: пустой список
-- рабочих дней, раскладку из нуля дней и сумму часов, которая никогда не
-- сойдётся с оценкой. Проверка на уровне базы, а не только в маршруте, потому
-- что запись сюда идёт и из формы постановки, и из переноса, и из разбиения.
ALTER TABLE task_parts
  DROP CONSTRAINT IF EXISTS task_parts_window_order;
ALTER TABLE task_parts
  ADD CONSTRAINT task_parts_window_order
  CHECK ("startDate" IS NULL OR "startDate" <= "dueDate");

-- «График» и доска спрашивают задачи, чей срок попадает в показанный период.
CREATE INDEX IF NOT EXISTS tasks_due_date ON tasks ("dueDate");

-- Многодневная подзадача выбирается по пересечению окна с периодом, и без
-- индекса по началу окна это seq scan по всем подзадачам на каждом открытии
-- графика.
CREATE INDEX IF NOT EXISTS task_parts_start_date ON task_parts ("startDate");

COMMIT;
