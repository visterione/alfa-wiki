-- Догоняющий ИИ-звонок: настоящий API партнёра и обратный путь (ver. 8.95).
--
-- В 8.52 модуль звонков выкатили без спецификации партнёра: формат лида был наш
-- собственный, а адрес, ключ и имя заголовка вписывались в карточке филиала.
-- Теперь партнёр известен — LPTracker (docs.direct.lptracker.ru), — и выяснилось
-- главное: проект у него уже подготовлен под наши визиты. В нём заведены поля
-- appointment_id, patient_name, clinic_title, time_start, doctor_name, mobile и
-- шаги воронки «Обзвон роботом», «Подтвердил», «Отменил», «AI · Не дозвонились».
-- Поэтому произвольный адрес заменён на доступ к их API, а состав лида — на их
-- имена полей (сопоставление по имени, см. services/notifications/lptracker.js).
--
-- ПОЧЕМУ ДОСТУП СТАЛ ОБЩИМ НА СЕТЬ. В 8.52 счёт CRM лёг на филиал — по той же
-- причине, по какой на филиал лёг счёт Имобиса в 8.25. Проверка живого аккаунта
-- показала другое: проект у партнёра один на всю сеть («Медцентр Альфа»), и
-- разводить лиды по клиникам он собирается полем clinic_title, а не отдельными
-- проектами. Поэтому логин, пароль и проект теперь общие, а у филиала остались
-- включатель и возможность указать свой проект и шаг воронки, если они у него
-- когда-нибудь появятся. Это не отмена прежнего решения, а приведение настройки
-- к тому, что в аккаунте партнёра есть на самом деле.
--
-- ОБРАТНЫЙ ПУТЬ. Приёмник итога звонка — POST /api/public/v1/ai-call/result,
-- ключ с правом ai-call:result из «Интеграций». По итогу «подтвердил» и
-- «отменил» портал зовёт те же confirmAppointment и cancelAppointment, что и
-- кнопка в боте. Без него звонок ничего не менял: визит оставался активным, и
-- администратор узнавал о неявке в день приёма.

BEGIN;

-- ── Доступ к CRM: общий на сеть ───────────────────────────────────────────

-- Пароль лежит открытым текстом — так же, как токены ботов в messenger_bots и
-- ключи Имобиса в notif_branch_settings.imobis. Шифрование потребовало бы ключа
-- шифрования, а он лёг бы в тот же .env, от которого мы уходим; доступ к таблице
-- равен доступу к серверу, и разделить их нам нечем.
-- Проект и шаг воронки вписаны сразу, логин и пароль — нет. Разница не в лени, а
-- в правиле: секреты в репозитории не лежат, их вводят в интерфейсе. Номера же
-- секретом не являются, взяты из живого аккаунта и избавляют от четырёх полей при
-- запуске: 139814 — проект «Медцентр Альфа», единственный в аккаунте; 2416247 —
-- шаг «Обзвон роботом», с которого партнёр запускает автоворонку обзвона (решение
-- заказчика). Оба меняются в интерфейсе выбором из списка.
INSERT INTO settings (key, value, description, "createdAt", "updatedAt")
VALUES (
  'notif_ai_call',
  '{"projectId": "139814", "funnelId": "2416247"}'::jsonb,
  'Доступ к CRM партнёра для ИИ-звонков: { login, password, projectId, funnelId }',
  now(), now()
)
ON CONFLICT (key) DO NOTHING;

-- Прежняя настройка филиала описывала произвольный адрес и ключ, которых больше
-- нет. Оставить их значило бы держать в базе доступ, ведущий в никуда, и однажды
-- потратить час на вопрос, почему он не действует. Включатель сохраняем: именно
-- он отвечает на вопрос, звонит ли этот филиал вообще.
UPDATE notif_branch_settings
SET ai_call = jsonb_strip_nulls(jsonb_build_object('enabled', ai_call -> 'enabled'))
WHERE ai_call IS NOT NULL;

COMMENT ON COLUMN notif_branch_settings.ai_call IS
  'ИИ-звонки у филиала: { enabled, projectId?, funnelId? }. Доступ общий на сеть — settings.notif_ai_call (ver. 8.95)';

-- ── Итог звонка ───────────────────────────────────────────────────────────

ALTER TABLE notif_call_requests
  ADD COLUMN IF NOT EXISTS lead_id     varchar(32),
  ADD COLUMN IF NOT EXISTS contact_id  varchar(32),
  ADD COLUMN IF NOT EXISTS result      varchar(20),
  ADD COLUMN IF NOT EXISTS result_at   timestamptz,
  ADD COLUMN IF NOT EXISTS result_raw  jsonb,
  ADD COLUMN IF NOT EXISTS mis_status  varchar(12),
  ADD COLUMN IF NOT EXISTS mis_error   text;

COMMENT ON COLUMN notif_call_requests.lead_id IS
  'Лид у партнёра: по нему заявка и разговор сходятся в одну историю';
COMMENT ON COLUMN notif_call_requests.result IS
  'Чем кончился разговор: confirmed, cancelled, no_answer, voicemail, hangup, callback, operator, unclear, other';
COMMENT ON COLUMN notif_call_requests.mis_status IS
  'Что получилось сделать в МИС по итогу: confirmed, cancelled, none, failed';

-- Итог ищется по визиту, а не по заявке: партнёр знает appointment_id и не
-- обязан помнить наш uuid. Индекс по appt_id уже есть с 8.52 — этого достаточно.

COMMIT;
