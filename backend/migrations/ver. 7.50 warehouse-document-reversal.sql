-- Точечная отмена операции: сторнирующий документ.
--
-- До этого исправить ошибку можно было двумя способами, и оба плохи. Первый —
-- оформить встречную операцию руками через вкладку «Операции»: четыре поля,
-- выбор кабинета из сотни и никакой связи с тем, что исправляют. Второй —
-- админский откат размещения по кабинету целиком, который стирает след; он
-- заведён для отладки на боевой базе и точечной ошибке не помощник.
--
-- Отсюда сторно: встречный документ, ссылающийся на исходный. Удаления нет и не
-- будет — удалённая проводка уносит из истории и саму ошибку, и то, что её
-- исправили, а отчёт № 2 обязан показывать обе записи.
--
-- Ссылка одна и в одну сторону: «этот документ отменяет тот». Обратная —
-- «этот документ отменён» — выводится из неё же, поэтому второго поля нет:
-- два поля рано или поздно разойдутся.
--
-- BEGIN/COMMIT здесь нет намеренно: файл применяется скриптом, и транзакцию
-- открывает он. Тем, кто применяет файл через psql, нужен флаг -1.

ALTER TABLE warehouse_documents
  ADD COLUMN IF NOT EXISTS "reversalOfId" UUID REFERENCES warehouse_documents(id)
    ON UPDATE CASCADE ON DELETE SET NULL;

-- Дважды один документ не сторнируется: второй раз он вернул бы то, чего уже
-- нет, а в истории появилась бы пара взаимоуничтожающих проводок без причины.
CREATE UNIQUE INDEX IF NOT EXISTS warehouse_documents_reversal_uniq
    ON warehouse_documents ("reversalOfId")
 WHERE "reversalOfId" IS NOT NULL;
