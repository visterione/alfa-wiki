-- Удаление первого поколения онбординга (ver. 8.39).
--
-- Модуль «Онбординг врача» (ver. 7.30) заменён разделом «Вакансии» (ver. 8.20):
-- тот умеет всё то же самое, плюс произвольный процесс, конструктор анкеты и
-- шаблоны должностей. Переноса заявок между поколениями не было и не будет —
-- это решение принято ещё при старте второго поколения, и здесь оно приводится
-- в исполнение.
--
-- Код модуля удалён целиком: маршруты, службы, модели, экраны в вебе и в
-- мобильном приложении, публичный контур /anketa. Эта миграция убирает то, что
-- в коде не лежит, — таблицы и флаг права.
--
-- ОТМЕНИТЬ НЕЛЬЗЯ. Вместе с таблицами уходят анкеты кандидатов, их файлы,
-- задачи, журнал и настройки чатов первого поколения. Сделайте резервную копию
-- базы до применения (npm run backup из backend) — это единственный способ
-- вернуть данные.

BEGIN;

-- Порядок не важен: CASCADE снимает внешние ключи между таблицами модуля.
-- Ссылок из чужих таблиц на onb_* нет — второе поколение не делило с первым
-- ничего, и именно поэтому удаление помещается в один блок.
DROP TABLE IF EXISTS onb_service_choices CASCADE;
DROP TABLE IF EXISTS onb_files          CASCADE;
DROP TABLE IF EXISTS onb_events         CASCADE;
DROP TABLE IF EXISTS onb_tasks          CASCADE;
DROP TABLE IF EXISTS onb_email_codes    CASCADE;
DROP TABLE IF EXISTS onb_chat_links     CASCADE;
DROP TABLE IF EXISTS onb_assignments    CASCADE;
DROP TABLE IF EXISTS onb_applications   CASCADE;

-- Флаг права из карточек пользователей. Переключателя в интерфейсе больше нет,
-- и оставленный ключ означал бы право, которое никто не может ни выдать, ни
-- снять, — а в выгрузке прав он выглядел бы действующим.
UPDATE users
   SET "adminAccess" = "adminAccess" - 'onboarding'
 WHERE "adminAccess" ? 'onboarding';

COMMIT;

-- Файлы кандидатов первого поколения лежат в backend/uploads/onboarding — их
-- эта миграция не трогает, они удаляются руками (см. command.txt).
--
-- ВАЖНО: каталог backend/uploads/onboarding-chats удалять НЕЛЬЗЯ. Несмотря на
-- имя, в нём лежат аватарки рабочих чатов, которые показывает «Добро
-- пожаловать» второго поколения: служба chatPreview.js вынесена из первого
-- модуля и осталась общей, а каталог не переименовывали, чтобы не сделать
-- битыми пути, уже записанные в базе.
