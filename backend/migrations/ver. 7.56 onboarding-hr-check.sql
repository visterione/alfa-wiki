-- ver. 7.56 — новый шаг онбординга «Проверка отделом кадров» (hr_check).
--
-- Схему менять не нужно: шаги живут в коде (services/onboarding/process.js), а
-- назначения — строками в onb_assignments с текстовым stepKey. Миграция нужна
-- ровно из-за одного: чек-лист готовности собирается из шагов, и заявки,
-- согласованные до выката, без задачи по новому шагу никогда не дошли бы до
-- «Запущен» — пункт остался бы вечно незакрытым, а открыть его было бы нечем.
--
-- Поэтому открываем hr_check тем заявкам, которые сейчас в работе.
--
-- Уже запущенные (launched) не трогаем: их процесс закончен, а новая открытая
-- задача только выдала бы кадрам список врачей, которые давно принимают.
-- Черновики, анкеты на согласовании и доработке тоже пропускаем — им задачу
-- поставит согласование главврача.
--
-- Задачу на создание учётки у этих заявок не отзываем, хотя по новому порядку
-- она должна ждать кадры. Она уже лежит у администратора МИС, и снять её значит
-- забрать из списка работу, которую человек, возможно, уже делает. Для десятка
-- заявок в переходный момент кадры и учётка разойдутся параллельно — это
-- дешевле, чем сломать людям текущую очередь. Со следующей согласованной анкеты
-- порядок работает как задумано.
--
-- Исполнителя не подставляем: назначения по новому шагу ещё нет. Задача
-- остаётся открытой с пустым assigneeIds, а когда администратор укажет отдел
-- кадров в настройках раздела, PUT /api/onboarding/settings/hr_check пересчитает
-- исполнителей у всех открытых задач шага — включая эти.
--
-- Срок отсчитываем от выката, а не от согласования: до сегодняшнего дня шага не
-- существовало, и просрочка «с прошлого месяца» была бы ложной. Двое суток —
-- календарный эквивалент 16 рабочих часов из process.js.
--
-- Миграция идемпотентна: повторный запуск не создаст вторую задачу, её ловит
-- уникальный индекс onb_tasks_app_step_uniq.

INSERT INTO onb_tasks ("applicationId", "stepKey", "assigneeIds", "dueAt")
SELECT a.id, 'hr_check', '[]'::jsonb, NOW() + INTERVAL '2 days'
  FROM onb_applications a
 WHERE a.status IN ('approved', 'mis_created')
ON CONFLICT ("applicationId", "stepKey") DO NOTHING;
