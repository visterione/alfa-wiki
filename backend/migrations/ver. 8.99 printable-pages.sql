-- Страницы, доступные для печати (ver. 8.99).
--
-- Сотрудники могут выгрузить выбранные страницы вики одним документом Word.
-- В него попадают только страницы, которые автор явно отметил: html-страница
-- бывает приложением со скриптами, и на бумаге от неё осталась бы пустая
-- оболочка. Поэтому по умолчанию флаг выключен у всех, включая существующие.
-- Отдельная колонка, а не ключ в metadata, — по ней идёт отбор при выгрузке.

ALTER TABLE pages ADD COLUMN IF NOT EXISTS "isPrintable" BOOLEAN NOT NULL DEFAULT false;
