-- ver. 6.34 — Колонка сравнения привязана к клинике парсера, а не к её названию
--
-- До этого связь держалась на совпадении строк: у источника было отдельное
-- «Название в сравнениях» (competitor_sources."competitorLabel"), и колонка
-- считалась его, если называлась так же или начиналась с «<название> — ».
-- У клиники получалось два имени: одно в парсере, второе — для сравнений;
-- какое из них где, путались все. Переименование клиники при этом молча
-- отрывало колонку от цен.
--
-- Теперь связь явная и лежит в самом сравнении. Имя колонки становится
-- обычной подписью — его можно менять, цены находят колонку по id.
--
-- Формат:
--   { "Неомед (Краснодар) — Красная": { "parserSourceId": 12, "filialId": 3 } }
-- filialId = null означает «вся клиника»: в колонку идут цены всех филиалов,
-- а из нескольких берётся минимальная.
ALTER TABLE price_comparisons
  ADD COLUMN IF NOT EXISTS "competitorBindings" JSONB NOT NULL DEFAULT '{}'::jsonb;

