-- Координаты и адреса филиалов для карты на экране входа (ver. 7.82).
--
-- Поля address, city, lat и lng в справочнике были с ver. 6.67, но пустые: до
-- карты они никому не были нужны. Карта на экране входа ставит метку по
-- координате и молча пропускает филиал, у которого её нет, — то есть без этой
-- заливки экран входа показывает пустую карту.
--
-- Откуда координаты: адреса продиктованы заказчиком, прогнаны через геокодер
-- OpenStreetMap (Nominatim). Четыре попали в дом, четыре — только в отрезок
-- улицы: этих домов в OSM нет. Помечены ниже; промах там до нескольких сотен
-- метров, и их стоит поправить руками по карте. Дом «Владимирская, 93» в OSM
-- подписан как «Медицинский центр Альфа» — этот адрес сошёлся сам собой.
--
-- Ничего не перезаписываем: COALESCE оставляет то, что уже введено в админке.
-- Повторный запуск безвреден.
--
-- Чего здесь нет и почему:
--   • «Неолаб» — новый медцентр, в справочнике его пока нет вовсе. Завести его
--     строкой в миграции нельзя: медцентр появляется в выборе у пользователей,
--     в метках чата, в отчётах и в правах, и это решение не миграции. Заводить
--     в админке, адрес — Анапа, Владимирская, 104.
--   • «ИП Микаелян» — по словам заказчика не заведение, а служебная запись.
--     Координат не даём намеренно: без них карта его не покажет.

UPDATE med_centers AS m SET
  city    = COALESCE(m.city, v.city),
  address = COALESCE(m.address, v.address),
  lat     = COALESCE(m.lat, v.lat),
  lng     = COALESCE(m.lng, v.lng)
FROM (VALUES
  -- по дому
  ('Альфа', 'Анапа', 'Владимирская, 93',  44.8804053, 37.3303100),
  ('Смайл', 'Анапа', 'Владимирская, 93',  44.8804053, 37.3303100),
  ('Кидс',  'Анапа', 'Астраханская, 98',  44.8819372, 37.3302617),
  ('Линия', 'Анапа', 'Ленина, 158',       44.8760013, 37.3248157),
  -- по соседнему дому: у «Проф» адрес 61/1, в OSM есть только 61
  ('Проф',  'Анапа', 'Парковая, 61/1',    44.8921781, 37.3385178),
  ('3К',    'Анапа', 'Ленина, 190к1',     44.8677232, 37.3330990),
  -- по отрезку улицы: дома в OSM нет, уточнить руками
  ('Сукко', 'Сукко', 'Утришская, 33',     44.7793929, 37.3937547)
) AS v(name, city, address, lat, lng)
WHERE m.name::text = v.name;

