'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');

const { readPhone } = require('../services/messengers/dialog');

// Номер, набранный руками, — второй путь знакомства наравне с кнопкой
// «поделиться контактом» (ver. 8.08). Ошибка разбора здесь не видна снаружи:
// подписка проходит, а напоминания уходят в пустоту или чужому человеку, и
// узнаём мы об этом через месяц. Отсюда подробность проверок.

test('номер принимается в любом привычном написании', () => {
  const written = [
    '+7 999 123-45-67',
    '+79991234567',
    '89991234567',
    '8 (999) 123-45-67',
    '8-999-123-45-67',
    '+7(999)123.45.67',
    '7 999 123 45 67',
    // Без кода страны — так номер диктуют вслух.
    '9991234567',
    // «+8» никакой стране не соответствует, но набирают так регулярно: человек
    // ставит плюс по привычке и восьмёрку по памяти.
    '+8 999 123 45 67'
  ];

  for (const raw of written) {
    assert.deepEqual(readPhone(raw), { status: 'ok', phone: '79991234567' }, raw);
  }
});

test('номер с потерянной цифрой не достраивается до правдоподобного', () => {
  // misClient.normalizePhone добавляет семёрку к десятизначному номеру, поэтому
  // «+7 999 123 45 6» без проверки длины превратился бы в 77999123456 — номер,
  // который выглядит настоящим и никому не принадлежит.
  assert.deepEqual(readPhone('+7 999 123 45 6'), { status: 'malformed' });
  assert.deepEqual(readPhone('99912345678'), { status: 'malformed' });
  assert.deepEqual(readPhone('999 12 34'), { status: 'malformed' });
  // Десятизначный без кода страны — только мобильный, он начинается с девятки.
  assert.deepEqual(readPhone('4951234567'), { status: 'malformed' });
  assert.deepEqual(readPhone('59991234567'), { status: 'malformed' });
});

test('обычный текст остаётся текстом и уходит оператору', () => {
  // null здесь означает «это не попытка назвать номер»: такое сообщение нельзя
  // ни разбирать, ни отвечать на него подсказкой про формат.
  for (const raw of ['здравствуйте', 'Мой номер 89991234567', 'запишите меня на приём', '2026', '', '   ', null]) {
    assert.equal(readPhone(raw), null, JSON.stringify(raw));
  }
});
