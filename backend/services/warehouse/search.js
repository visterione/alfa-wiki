/**
 * Поиск по названиям в складском модуле.
 *
 * ── Что было не так ──────────────────────────────────────────────────────────
 *
 * Каждый список искал по-своему, и все три способа теряли строки:
 *
 *   • подстрокой целиком. «системный блок» не находил «Блок системный HP», а
 *     «компьютер hp» — «Компьютер HP ProDesk»: слова в названиях из 1С стоят в
 *     любом порядке, и человек набирает их тоже в любом;
 *   • без «ё». В ведомости соседствуют «Ёмкость» и «Емкость», «Свёрла» и
 *     «Сверла» — набравший одно не находил другого, и это выглядело как
 *     пропавшие позиции;
 *   • с шаблонными символами LIKE. Запрос «НДС 20%» превращался в шаблон, где
 *     процент значит «что угодно», и находил лишнее.
 *
 * ── Правило ──────────────────────────────────────────────────────────────────
 *
 * Запрос дробится на слова, и строка подходит, когда КАЖДОЕ слово нашлось хоть
 * в одном из полей — в любом порядке и в любом месте. Это ровно то, чего ждёт
 * человек, набирающий «компьютер hp»: он перечисляет приметы вещи, а не пишет
 * её название по памяти.
 *
 * Сравнение идёт по translate(lower(поле), 'ё', 'е'): «ё» и «е» для поиска один
 * и тот же звук, и держать две буквы в базе — забота учёта, а не ищущего.
 *
 * Индекс на таком выражении не используется, и это осознанно: поиск по
 * подстроке '%…%' его и так не использует, а строк в складских справочниках
 * тысячи, а не миллионы.
 */

const { Op } = require('sequelize');
const { sequelize } = require('../../models');

/**
 * Запрос → список слов для сравнения.
 *
 * Слова короче двух букв отбрасываются: «в», «и» и одиночные буквы есть почти в
 * каждом названии, и от них поиск не сужается, а только тормозит.
 *
 * Но если после отсева не осталось ничего, берём что дали. Иначе запрос «3»
 * (номер кабинета) или «ПК» превращался бы в пустой — то есть в «показать всё»,
 * а это ровно противоположно тому, чего от поиска ждут.
 */
function searchWords(q) {
  const all = String(q || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/[\s,;]+/)
    .map(w => w.trim())
    .filter(Boolean);

  const long = all.filter(w => w.length >= 2);
  // % и _ — шаблонные символы LIKE, и в названиях они законны: «НДС 20%»,
  // «шкаф_2». Экранируем обратной косой чертой — это escape по умолчанию.
  return (long.length ? long : all).map(w => w.replace(/[\\%_]/g, m => `\\${m}`));
}

/**
 * Условие «каждое слово запроса нашлось хоть в одном из полей».
 *
 * @param {string} q        строка запроса
 * @param {string[]} columns полные имена колонок («name», «nomenclature.name»)
 * @returns {object|null}   фрагмент where или null, когда искать нечего
 */
function searchWhere(q, columns) {
  const words = searchWords(q);
  if (!words.length || !columns.length) return null;

  const wordMatches = word => ({
    [Op.or]: columns.map(column => sequelize.where(
      sequelize.fn('translate', sequelize.fn('lower', sequelize.col(column)), 'ё', 'е'),
      { [Op.like]: `%${word}%` },
    )),
  });

  return { [Op.and]: words.map(wordMatches) };
}

/**
 * То же правило для списков, уже загруженных в память: тем спискам, которые
 * приходят целиком, второй запрос к базе ни к чему, а расходиться с серверным
 * поиском они не должны.
 *
 * @param {string} q       строка запроса
 * @param {string[]} values значения полей строки
 */
function matchesSearch(q, values) {
  const words = searchWords(q).map(w => w.replace(/\\([\\%_])/g, '$1'));
  if (!words.length) return true;
  const hay = values.filter(Boolean).join(' ').toLowerCase().replace(/ё/g, 'е');
  return words.every(word => hay.includes(word));
}

module.exports = { searchWords, searchWhere, matchesSearch };
