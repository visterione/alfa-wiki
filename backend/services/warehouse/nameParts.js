/**
 * Разбор названия позиции на составляющие: модель, производитель, габариты.
 *
 * ── Зачем ────────────────────────────────────────────────────────────────────
 *
 * В ведомости 1С модель написана прямо в названии — «МФУ Pantum M6700DW
 * лазерный», «Аппарат озонотерапии АОТ-Н-01-Арз-01/1», — а в карточке портала
 * поле «модель» остаётся пустым: разбор кладёт название целиком в наименование и
 * больше ничего с ним не делает. По августовской выгрузке это 3173 карточки, у
 * которых модель не заполнена ни у одной.
 *
 * ── Что здесь можно и чего нельзя ────────────────────────────────────────────
 *
 * Разбор эвристический, и это признаётся честно: правил, которые разберут любое
 * название из 1С, не существует. Поэтому функция ничего не решает сама — она
 * возвращает предложение вместе с признаком того, что именно нашла, а применять
 * его или нет, решает вызывающий код. Наименование при этом НЕ трогается: имя
 * позиции остаётся ровно тем, что в ведомости, иначе сверка с бухгалтерией
 * перестала бы сходиться по названию.
 *
 * ── Что считается моделью ────────────────────────────────────────────────────
 *
 * Токен с цифрами, который не является измерением. Это отличие принципиальное:
 * «M6700DW», «RB4011iGS+RM», «АОТ-Н-01» — модели, а «2,8мм», «8ГБ», «1080р»,
 * «720*300*700» — характеристики. Без отсечения измерений разбор наполнял бы
 * поле «модель» диагоналями мониторов и объёмами дисков, а такую ошибку заметили
 * бы только через год, когда по модели попытались бы искать запчасти.
 *
 * ── Что считается производителем ─────────────────────────────────────────────
 *
 * Латинское слово непосредственно перед моделью: «Dahua DHI-LM24-B201E»,
 * «Philips TAH2005BK». Именно перед — потому что в 1С порядок «тип, бренд,
 * модель» выдержан почти всегда, а вот словаря брендов у нас нет и завести его
 * значило бы поддерживать список из сотен строк ради поля, которое и так
 * выводится из позиции слова.
 */

// Единицы измерения и служебные хвосты: всё, что ими заканчивается, — не модель.
// Список закрытый и короткий намеренно: это не попытка перечислить все единицы
// мира, а перечень того, что реально встречается в ведомости рядом с цифрами.
const UNIT_TAIL = /^(мм|см|м|км|кг|г|мг|л|мл|шт|уп|гб|тб|мб|кб|вт|квт|в|ма|а|ва|гц|мгц|ч|мин|сек|дюйм|"|р|рм|об|бит|ядер|эт|каб|мес|год|лет)$/i;

// Габариты: 2000*500*2200, 700х420х810 мм, 40*60см, 145*210.
//
// Заканчивается выражение не на \b, а на явную проверку «дальше не буква и не
// цифра». Причина неочевидная и стоила отладки: \b в JavaScript определён по
// ASCII-словам, кириллическая «м» словарным символом для него не является, и
// после «800мм» границы слова не возникает. С \b единица измерения не
// захватывалась НИКОГДА — габариты молча теряли «мм», и заметно это было только
// на глаз в отчёте.
const DIMENSIONS = /\b\d{1,5}(?:[.,]\d+)?\s*[*х×x]\s*\d{1,5}(?:[.,]\d+)?(?:\s*[*х×x]\s*\d{1,5}(?:[.,]\d+)?)?\s*(?:мм|см|м)?(?![A-Za-zА-Яа-яЁё0-9])/i;

// Хвост в скобках — комплектация и характеристики: «(упаковочная машина)»,
// «(охватывающие; открытые, каб.2м, разъем 3,5мм)». В наименовании он не нужен,
// в примечании полезен.
const PARENS = /\(([^()]{2,200})\)/g;

const LATIN = /^[A-Za-z][A-Za-z&.'-]*$/;
const HAS_DIGIT = /\d/;

/**
 * Похоже ли слово на модель.
 *
 * Требуется цифра и хотя бы одна буква или дефис: чистое число — это количество,
 * год или размер, но не модель. «5» из «Cubi 5» отсекается здесь же, и это
 * правильный компромисс: короткие числовые модели встречаются, но принять их
 * значит принять и все размеры подряд.
 */
/**
 * Токен без обрамляющей пунктуации. Одна функция на весь модуль намеренно: если
 * проверка «похоже на модель» и запись в поле чистят строку по-разному, в
 * карточку однажды попадёт «арт.30120TQ» при том, что проверку прошло
 * «30120TQ», — и разойдутся они молча.
 */
function cleanToken(token) {
  return String(token)
    .replace(/^[«"'(]+|[»"'),.;:]+$/g, '')
    // Префикс «арт.» — служебное слово 1С, а не часть обозначения.
    .replace(/^(арт|art)\.?/i, '');
}

function looksLikeModel(token) {
  const clean = cleanToken(token);
  if (clean.length < 2 || clean.length > 40) return false;
  if (!HAS_DIGIT.test(clean)) return false;

  // Отсекаем измерения: 8ГБ, 2,8мм, 1080р, 60см.
  const measurement = clean.match(/^\d+(?:[.,]\d+)?([A-Za-zА-Яа-яё"]+)$/);
  if (measurement && UNIT_TAIL.test(measurement[1])) return false;
  // Чистое число или число с запятой — не модель.
  if (/^\d+(?:[.,]\d+)?$/.test(clean)) return false;
  // Габариты внутри токена: 720*300*700.
  if (/[*х×x]/i.test(clean) && /^\d/.test(clean)) return false;
  // Артикулы вида 30.0130.20 — это код 1С, а не модель прибора.
  if (/^\d+(\.\d+){2,}$/.test(clean)) return false;

  // ── Отсечения, добавленные после прогона по августовской выгрузке ──────────
  // Каждое закрывает конкретный класс ложных срабатываний, который в ней виден.

  // Числительные с наращением: «с 3-мя ящиками», «2-х камерный».
  if (/^\d+[-–][а-яё]{1,3}$/i.test(clean)) return false;
  // Составные единицы: «130мм/шт», «10мл/фл». Начинается с цифры и содержит дробь.
  if (/^\d/.test(clean) && clean.includes('/')) return false;
  // Обрывки после скобок: «-7-6» из «СПБ (пс)-7-6».
  if (/^[-–]/.test(clean)) return false;
  // Номер позиции, а не модель: «отверст.№1», «№15».
  if (clean.includes('№')) return false;
  // Характеристика с явным знаком равенства: «D=230мм» — это диаметр, и в поле
  // «модель» он выглядит убедительно ровно до первой попытки заказать запчасть.
  if (clean.includes('=')) return false;
  // Модель почти всегда содержит заглавную букву: «LD-80», «КГ-02», «M28w».
  // Без этого в поле попадают обрывки строчных слов с цифрами.
  if (!/[A-ZА-ЯЁ]/.test(clean)) return false;
  // Двухсимвольные обрывки вроде «2G» из «МД SP 2G» слишком часто оказываются
  // характеристикой, а не моделью. Настоящая короткая модель почти всегда имеет
  // разделитель — «Х-1», «СБ9» проходят по длине три.
  if (clean.length < 3 && !/[-.]/.test(clean)) return false;

  return /[A-Za-zА-Яа-яЁё-]/.test(clean);
}

/** Единицы и мусорные слова, которые не могут быть производителем. */
function looksLikeBrand(token) {
  const clean = cleanToken(token);
  if (clean.length < 2 || clean.length > 24) return false;
  if (!LATIN.test(clean)) return false;
  if (UNIT_TAIL.test(clean)) return false;
  // Бренд пишется с заглавной: «Dahua», «MIKROTIK». Строчное слово перед моделью
  // — это описание («лазерный M28w»), а не производитель.
  if (!/^[A-Z]/.test(clean)) return false;
  // Слова-описания и типы устройств в латинице, которые брендами не бывают.
  // Список выведен из ложных срабатываний на августовской выгрузке: «МФУ HP
  // LaserJet MFP M28w» давало производителя MFP, «Тонометр CS Medical CS-106» —
  // производителя Medical.
  return !/^(new|set|pro|plus|max|mini|type|for|and|with|ip|usb|hd|led|lcd|ssd|hdd|wifi|dc|ac|mfp|laserjet|deskjet|officejet|inkjet|medical|series|mod|model|art|ref|smart)$/i.test(clean);
}

/**
 * Разбор одного названия.
 *
 * @returns {{name, model, manufacturer, dimensions, extras, found}}
 *   name         — наименование без габаритов и скобок; исходное НЕ заменяется
 *   model        — найденный токен модели или null
 *   manufacturer — латинское слово перед моделью или null
 *   dimensions   — габариты строкой или null
 *   extras       — содержимое скобок, склеенное через «; »
 *   found        — какие поля удалось выделить
 */
function splitName(rawName) {
  const source = String(rawName || '').replace(/[\s ]+/g, ' ').trim();
  if (!source) {
    return { name: '', model: null, manufacturer: null, dimensions: null, extras: null, found: [] };
  }

  // 1. Скобки — в примечание.
  const extras = [];
  let rest = source.replace(PARENS, (_, inner) => {
    extras.push(inner.trim());
    return ' ';
  });

  // 2. Габариты — в отдельное поле.
  const dimMatch = rest.match(DIMENSIONS);
  const dimensions = dimMatch ? dimMatch[0].replace(/\s+/g, '').replace(/[х×x]/gi, '×') : null;
  if (dimMatch) rest = rest.replace(dimMatch[0], ' ');

  // 3. Модель и производитель.
  // Двоеточие разделяет токены наравне с пробелом: «серии СМ:СМ-50» — это два
  // обозначения подряд, а не одно длинное.
  const tokens = rest.split(/[\s,;:]+/).filter(Boolean);
  let model = null;
  let manufacturer = null;

  for (let i = 0; i < tokens.length; i++) {
    if (!looksLikeModel(tokens[i])) continue;
    model = cleanToken(tokens[i]);
    // Производитель ищется назад от модели, но не ближайшим словом, а самым
    // «брендовым» из трёх предыдущих. Между брендом и моделью почти всегда стоит
    // продуктовая линейка: «ACER Veriton VN4640G», «KYOCERA Ecosys P2040DN»,
    // «DEXP Aquilon O292». Ближайшее слово дало бы линейку, а не производителя,
    // и в карточке появился бы «Veriton» вместо Acer.
    //
    // Различает их регистр: бренд в 1С почти всегда набран заглавными или хотя бы
    // не уступает линейке, поэтому CAPS-слово в пределах трёх токенов выигрывает.
    let fallback = null;
    for (let back = 1; back <= 3 && i - back > 0; back++) {
      const candidate = cleanToken(tokens[i - back]);
      if (!looksLikeBrand(candidate)) continue;
      if (candidate.length >= 3 && candidate === candidate.toUpperCase()) {
        manufacturer = candidate;
        break;
      }
      if (!fallback) fallback = candidate;
    }
    if (!manufacturer) manufacturer = fallback;
    break;
  }

  // 4. Наименование без вынесенного.
  let name = rest;
  if (model) name = name.replace(model, ' ');
  if (manufacturer) name = name.replace(new RegExp(`\\b${escapeRe(manufacturer)}\\b`), ' ');
  name = name.replace(/[\s,;]+/g, ' ').replace(/\s+([,.;])/g, '$1').trim()
    .replace(/[-–,;]+$/, '').trim();

  const found = [];
  if (model) found.push('model');
  if (manufacturer) found.push('manufacturer');
  if (dimensions) found.push('dimensions');
  if (extras.length) found.push('extras');

  return {
    name: name || source,
    model,
    manufacturer,
    dimensions,
    extras: extras.length ? extras.join('; ') : null,
    found,
  };
}

const escapeRe = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

module.exports = { splitName, looksLikeModel, looksLikeBrand };
