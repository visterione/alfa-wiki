'use strict';

/**
 * Филиал портала по клинике визита МИС (ver. 8.17).
 *
 * До 8.17 сопоставление жило в трёх местах — в шаблонах, в отправщике и в
 * стоп-листе служебных врачей, — и все три искали филиал мимо справочника,
 * собственным запросом по названию:
 *
 *     lower(med_centers.name) = lower(appt.clinic)
 *
 * ЧТО БЫЛО НЕ ТАК. Названия совпадать не обязаны и не совпадают: в МИС клиника
 * зовётся «Альфа Линия», в справочнике портала — «Линия»; так же разошлись Кидс,
 * Проф, Смайл и Сукко. Промах ничем себя не выдавал: без филиала у события не
 * находится шаблон (с 8.11 общих текстов нет), а без шаблона событие не попадает
 * даже в журнал — по филиалу просто ничего не приходит, и выяснить причину можно
 * было только запросом в базу.
 *
 * Поэтому первичен идентификатор: misClinicIds заведён ровно для этой связи и
 * уже держит на себе расписание, зарплату, бонусы и платежи, а заодно схлопывает
 * исторические дубли (у Сукко их два). Имя осталось запасным вариантом — для
 * клиник, которым id в справочнике ещё не проставили.
 *
 * Своего кэша здесь нет намеренно. Справочник — это services/medCenters.js, он
 * уже держит индекс по misClinicIds и по имени и сбрасывается из маршрутов,
 * которые справочник правят. Три прежних сопоставления кэшировали результат
 * каждое по-своему, Map без срока, и филиал, заведённый после запуска процесса,
 * оставался невидимым до перезапуска.
 */

const medCenters = require('../medCenters');

/**
 * Филиал портала по снимку визита. Сначала по id клиники МИС, затем по имени.
 *
 * @param {{clinicId?:number|string, clinicName?:string}} snap
 * @returns {Promise<Object|null>} строка справочника вместе с юрлицом
 */
async function find(snap) {
  if (!snap) return null;

  const byMisId = await medCenters.byMisId(snap.clinicId);
  if (byMisId) return byMisId;

  return snap.clinicName ? await medCenters.byName(snap.clinicName) : null;
}

/** То же, но нужен только идентификатор филиала. */
async function idFor(snap) {
  const mc = await find(snap);
  return mc ? mc.id : null;
}

module.exports = { find, idFor };
